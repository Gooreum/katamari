import {
  BoxGeometry, CylinderGeometry, SphereGeometry, TorusGeometry,
  type BufferGeometry,
} from 'three';
import type { ShapeIdFurniture } from './generation';
import { assemble, DARK, INK, part, WHITE, WOOD, soft } from './shapes.kit';
import { TILE } from './atlas';

/** X축으로 돌린 원기둥·토러스 — 축이 Z가 된다 */
const LIE_Z: readonly [number, number, number] = [Math.PI / 2, 0, 0];
/** 눕힌 원기둥. 원기둥 축은 Y라 Z로 90° 돌리면 X축이 된다 */
const LIE_X: readonly [number, number, number] = [0, 0, Math.PI / 2];

/**
 * **거실 가구 형상 — 여섯 종.**
 *
 * ## 왜 이 파일이 생겼나
 *
 * 거실 가구는 `CityBuilding` 이었다 — 2D 외곽선을 y=0부터 위로 뽑는 것뿐이라
 * **프리즘밖에 못 만든다.** 그래서 화면에서 텔레비전이 상자 두 개, 서랍장이 상자
 * 세 개, 밥상이 각기둥 넷에 상판은 떠 있는 텍스처였다.
 *
 * **그런데 형상 자체는 이미 있었다.** `shapes.large.ts` 의 텔레비전은 다이얼 둘과
 * 안테나 둘까지 붙은 9부품이고, 서랍장은 서랍 3단, 스탠드는 갓과 전구가 있다.
 * 거실이 그걸 안 쓰고 있었을 뿐이다 — 손으로 「여기에 이 형상을 놓아라」고 말할
 * 경로가 없었기 때문이다(`StageProp` 이 그걸 뚫었다).
 *
 * 그래서 여기 있는 건 **그 목록에 아예 없던 것들**뿐이다:
 * TV장 · 책장 · 밥상 · 신문더미 · 화분대 · 방석더미.
 *
 * ## 상자와 가구를 가르는 것
 *
 * 덩어리 하나로는 절대 안 읽힌다. 그 물건을 그 물건으로 만드는 **한 끗**이 있다:
 *
 *   책장 → 선반 칸       밥상 → 상판       TV장 → 뚫린 아래 칸
 *   신문더미 → 어긋난 겹  화분대 → 다리 셋   방석더미 → 어긋나게 포갠 세 장
 *
 * 부품을 아끼면 그 한 끗이 먼저 죽는다. 가구는 화면에서 소품보다 훨씬 크게 보이고
 * 방마다 열댓 개뿐이라, 소품보다 부품을 넉넉히 써도 삼각형 예산에 여유가 있다.
 *
 * ## 규약
 *
 * 기존 빌더와 같다. `shapes.kit.ts` 만 import 하고(`shapes.ts` 를 import 하면 순환 참조),
 * 치수는 실제 cm 감각으로 쓰며, `assemble()` 의 `normalize()` 가 최장축을 1.0으로 맞춘다.
 * **`part()` 의 5번째 인자는 배율이 아니라 인쇄 칸 번호다.**
 */
export const FURNITURE_BUILDERS: Record<ShapeIdFurniture, () => BufferGeometry> = {

  /**
   * TV 받침대 (100cm).
   *
   * **아래 칸이 뚫려 있어야 장식장으로 읽힌다** — 통짜면 그냥 상자고, 그게 여태
   * 거실에 서 있던 것이다. 상판·측판·선반·뒷판을 따로 세워 칸을 만든다.
   */
  TV장: () => assemble([
    part(soft(1.00, 0.05, 0.46, 0.35), WHITE, [0, 0.42, 0], undefined, TILE.WOOD_C),        // 상판
    /**
     * **측판·뒷판이 가운데 선반 밑면(0.1825)에서 끊긴다.**
     *
     * 예전엔 바닥까지 내려오고 굽이 6cm 짜리 정육면체 넷이었다. 아래 칸이 앞에서
     * 뚫려 보이는데 충돌 상자는 바닥부터 꼭대기까지 통짜라, 사용자가
     * 「티비 선반 밑으로는 아예 들어가지지도 않고」라고 했다.
     *
     * 그 아래를 **다리 넷만** 남기면 `underPass: 0.18` 이 거짓말이 아니게 된다 —
     * 밑을 지나는 공이 통과하는 건 얇은 다리뿐이고, 그건 밥상이 이미 쓰는 규약이다.
     * **상판 0.42·가운데 선반 0.20 은 한 mm 도 안 움직인다** —
     * `surf-tv-shelf`(0.218)·`surf-tv-stand`(0.445)·`surf-tv-top`(0.760) 이 그 위에 얹힌다.
     */
    part(soft(0.05, 0.218, 0.46, 0.3), WHITE, [-0.475, 0.291, 0]),   // 측판
    part(soft(0.05, 0.218, 0.46, 0.3), WHITE, [0.475, 0.291, 0]),
    part(soft(0.90, 0.035, 0.44, 0.3), WOOD, [0, 0.20, 0]),          // 가운데 선반
    // 뒷판. **가운데 선반과 «같은 평면»을 안 만든다** — 폭 0.88·밑면 0.20 으로
    // 어긋내야 밑면과 옆면이 선반과 안 겹친다(자가 `3×4` 로 잡았다)
    part(new BoxGeometry(0.88, 0.20, 0.03), WOOD, [0, 0.30, -0.215]),
    // 다리 넷 — 18cm. 6cm 짜리 굽은 「띄웠다」로도 「붙였다」로도 안 읽혔다
    ...([[0.42, 0.18], [-0.42, 0.18], [0.42, -0.18], [-0.42, -0.18]] as const).map(
      ([x, z]) => part(soft(0.055, 0.1825, 0.055, 0.25), DARK, [x, 0.0913, z])),
  ]),

  /**
   * 책장 (105cm).
   *
   * **선반이 가로선을 그어야 칸이 생긴다.** 측판·뒷판만 있으면 벽에 붙은 판때기다.
   * 여태 거실 책장은 압출 조각 넷이라 세로선만 있었다.
   */
  책장: () => assemble([
    // 측판 — **굽 «위»에서 시작한다.** 둘 다 y=0 이면 밑면 두 장이 같은 평면이다
    part(soft(0.05, 0.94, 0.32, 0.3), WHITE, [-0.34, 0.535, 0], undefined, TILE.WOOD_C),
    part(soft(0.05, 0.94, 0.32, 0.3), WHITE, [0.34, 0.535, 0], undefined, TILE.WOOD_C),
    // 위 마감 — 측판보다 «살짝 넓게». 폭이 같으면 옆면이 같은 평면이라 z-fighting 이다
    // 위 마감 — 측판보다 «넓고», 밑면이 측판 윗면(1.005)과 겹치지 않게 살짝 물린다
    part(soft(0.78, 0.05, 0.35, 0.3), WHITE, [0, 0.985, 0], undefined, TILE.WOOD_C),
    // 뒷판 — 안쪽은 그늘이다. `PAPER`(대비 0.04)로는 측판과 한 덩어리
    // 뒷판은 «칸 안의 그늘»이다. 선반(WOOD)·측판(WHITE) 둘 다와 갈려야 칸이 보인다
    /**
     * 뒷판은 «칸 안의 그늘»이다. 선반·측판 둘 다와 갈려야 칸이 보인다.
     * **책장 팔레트가 나무색(밝기 0.46)이라 계수 차이가 0.46배로 눌린다** —
     * 문턱 0.15 를 넘기려면 계수 차이가 0.33 이상이어야 한다. 그늘답게 깊게 간다.
     */
    part(new BoxGeometry(0.66, 0.90, 0.03), [0.14, 0.12, 0.10], [0, 0.535, -0.157],
      undefined, TILE.WOOD_F),
    // 선반 셋 — 이게 책장의 정체다. 깊이를 측판보다 얕게 해서 «칸»이 보이게
    ...([0.30, 0.56, 0.82] as const).map((y) =>
      part(soft(0.68, 0.034, 0.29, 0.3), [0.88, 0.82, 0.74], [0, y, 0.008])),
    part(soft(0.76, 0.065, 0.34, 0.3), WOOD, [0, 0.0325, 0]),      // 굽
  ]),

  /**
   * 차부다이 (95cm) — 상에 둘러앉는 낮은 원형 상.
   *
   * **여태 이건 각기둥 넷이었고 상판은 그 위에 떠 있는 텍스처 평면이었다.**
   * 나무 판때기가 하나도 없었다. 상판 없는 상은 상이 아니다.
   */
  밥상: () => assemble([
    part(new CylinderGeometry(0.50, 0.50, 0.05, 20), WHITE, [0, 0.325, 0]),
    // 테두리 — 상판 옆면에 한 줄을 그어야 판이 두께를 갖는다
    part(new TorusGeometry(0.49, 0.022, 4, 20), WOOD, [0, 0.325, 0], LIE_Z),
    // 다리 넷. 상판 지름(1.0)보다 안쪽에 모아야 상다리로 보인다
    ...([[0.30, 0.30], [-0.30, 0.30], [0.30, -0.30], [-0.30, -0.30]] as const).map(
      ([x, z]) => part(new CylinderGeometry(0.030, 0.024, 0.30, 6), WOOD, [x, 0.15, z], undefined, TILE.WOOD_C)),
    // 다리를 잇는 가로대. 없으면 다리가 허공에 꽂힌 막대로 보인다
    part(soft(0.58, 0.025, 0.025, 0.35), WOOD, [0, 0.08, 0.30]),
    part(soft(0.58, 0.025, 0.025, 0.35), WOOD, [0, 0.08, -0.30]),
  ]),

  /**
   * 쌓아둔 신문 (45cm).
   *
   * **겹이 어긋나야 더미로 읽힌다** — 반듯하게 쌓으면 그냥 상자다.
   * 신문·찌라시 인쇄를 번갈아 물려 층마다 다른 지면이 나오게 한다.
   */
  신문더미: () => assemble([
    part(new BoxGeometry(1.00, 0.09, 0.66), WHITE, [0, 0.045, 0], [0, 0.04, 0], TILE.NEWSPAPER),
    // 층 — 신문지는 팔레트가 흰색이라 «짙은» 쪽으로 갈라야 겹이 보인다(PAPER 는 0.09)
    part(new BoxGeometry(0.96, 0.08, 0.64), [0.74, 0.73, 0.70], [0.02, 0.13, 0.02], [0, -0.06, 0]),
    part(new BoxGeometry(0.98, 0.08, 0.62), WHITE, [-0.02, 0.21, -0.01], [0, 0.09, 0], TILE.FLYER),
    part(new BoxGeometry(0.92, 0.07, 0.60), [0.78, 0.77, 0.74], [0.03, 0.28, 0.01], [0, -0.03, 0]),
    // 묶은 끈 둘. 더미를 묶어야 더미다
    part(new BoxGeometry(0.05, 0.34, 0.70), [0.55, 0.42, 0.30], [-0.24, 0.16, 0]),
    part(new BoxGeometry(0.05, 0.34, 0.70), [0.55, 0.42, 0.30], [0.24, 0.16, 0]),
  ]),

  /**
   * 화분대 (55cm) — 다리 셋짜리 낮은 원형 스탠드.
   * 아래 선반이 있어야 「대」로 읽힌다.
   */
  화분대: () => assemble([
    part(new CylinderGeometry(0.34, 0.34, 0.045, 20), WHITE, [0, 0.98, 0]),  // 상판
    part(new TorusGeometry(0.33, 0.018, 4, 20), WOOD, [0, 0.98, 0], LIE_Z),
    // 다리 셋. 120°씩
    ...([0, 2.0944, 4.1888] as const).map((a) =>
      part(new CylinderGeometry(0.028, 0.022, 0.96, 6), WOOD,
        [Math.cos(a) * 0.26, 0.48, Math.sin(a) * 0.26], undefined, TILE.WOOD_C)),
    part(new CylinderGeometry(0.20, 0.20, 0.03, 14), WOOD, [0, 0.26, 0]),    // 아래 선반
    // 다리를 묶는 가로대 — 없으면 다리 셋이 따로 논다
    part(new TorusGeometry(0.255, 0.014, 4, 20), WOOD, [0, 0.62, 0], LIE_Z),
  ]),

  /**
   * 개어 쌓아둔 방석 (50cm).
   * 세 장이 **어긋나게** 포개져야 쌓인 것으로 읽힌다.
   */
  방석더미: () => assemble([
    part(new SphereGeometry(0.5, 16, 10).scale(1, 0.20, 1), WHITE, [0, 0.05, 0]),
    // 가운데 방석 — 위아래와 밝기가 달라야 «더미»가 된다(PAPER 는 대비 0.09)
    part(new SphereGeometry(0.48, 16, 10).scale(1, 0.20, 1), [0.76, 0.74, 0.70],
      [0.03, 0.14, 0.02], [0, 0.22, 0], TILE.CLOTH),
    part(new SphereGeometry(0.46, 16, 10).scale(1, 0.20, 1), WHITE, [-0.02, 0.23, -0.02], [0, -0.16, 0]),
    // 가장자리 시접 — 방석을 방석으로 만드는 테두리
    // 시접·단추·술 — 꿰맨 자국은 «짙다». PAPER 는 천에 파묻힌다
    part(new TorusGeometry(0.42, 0.026, 6, 20), INK, [0, 0.045, 0], LIE_Z),
    part(new TorusGeometry(0.39, 0.024, 6, 20), INK, [-0.02, 0.235, -0.02], LIE_Z),
    part(new CylinderGeometry(0.05, 0.05, 0.025, 8), INK, [-0.02, 0.292, -0.02], undefined, TILE.CLOTH),
    part(new CylinderGeometry(0.014, 0.014, 0.10, 6), INK, [0.30, 0.05, 0.30], LIE_X),
  ]),
};
