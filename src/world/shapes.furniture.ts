import {
  BoxGeometry, ConeGeometry, CylinderGeometry, SphereGeometry, TorusGeometry,
  type BufferGeometry,
} from 'three';
import type { ShapeIdFurniture } from './generation';
import { assemble, part, pillow, soft, taper, warp, type RGB } from './shapes.kit';
import { TILE } from './atlas';


/**
 * **거실 가구 형상 — 여섯 종.**
 *
 * ## 왜 이 파일이 생겼나
 *
 * 거실 가구는 `CityBuilding` 이었다 — 2D 외곽선을 y=0부터 위로 뽑는 것뿐이라
 * **프리즘밖에 못 만든다.** 그래서 화면에서 텔레비전이 상자 두 개, 서랍장이 상자
 * 세 개, 밥상이 각기둥 넷에 상판은 떠 있는 텍스처였다.
 *
 * **그런데 형상 자체는 이미 있었다.** `shapes.large.ts` 의 텔레비전은 다이얼 둘과
 * 안테나 둘까지 붙은 9부품이고, 서랍장은 서랍 3단, 스탠드는 갓과 전구가 있다.
 * 거실이 그걸 안 쓰고 있었을 뿐이다 — 손으로 「여기에 이 형상을 놓아라」고 말할
 * 경로가 없었기 때문이다(`StageProp` 이 그걸 뚫었다).
 *
 * 그래서 여기 있는 건 **그 목록에 아예 없던 것들**뿐이다:
 * TV장 · 책장 · 밥상 · 신문더미 · 화분대 · 방석더미.
 *
 * ## 상자와 가구를 가르는 것
 *
 * 덩어리 하나로는 절대 안 읽힌다. 그 물건을 그 물건으로 만드는 **한 끗**이 있다:
 *
 *   책장 → 선반 칸       밥상 → 상판       TV장 → 뚫린 아래 칸
 *   신문더미 → 어긋난 겹  화분대 → 다리 셋   방석더미 → 어긋나게 포갠 세 장
 *
 * 부품을 아끼면 그 한 끗이 먼저 죽는다. 가구는 화면에서 소품보다 훨씬 크게 보이고
 * 방마다 열댓 개뿐이라, 소품보다 부품을 넉넉히 써도 삼각형 예산에 여유가 있다.
 *
 * ## 규약
 *
 * 기존 빌더와 같다. `shapes.kit.ts` 만 import 하고(`shapes.ts` 를 import 하면 순환 참조),
 * 치수는 실제 cm 감각으로 쓰며, `assemble()` 의 `normalize()` 가 최장축을 1.0으로 맞춘다.
 * **`part()` 의 5번째 인자는 배율이 아니라 인쇄 칸 번호다.**
 */
export const FURNITURE_BUILDERS: Record<ShapeIdFurniture, () => BufferGeometry> = {

  /**
   * TV장 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/TV장/` (다리 달린 두 단 TV대, 출품 치수 105.5 × 41.5 × 48cm)
   *
   * 앞의 것은 측판·가운데 선반·다리 넷의 상자형이었다. 사진은 더 가볍다:
   *   ① 너비 : 높이 : 깊이 = **1 : 0.455 : 0.39** — 낮고 긴 두 단
   *   ② 높이의 **0.48** 을 차지하는 아래로 가늘어지는 다리 넷(끝에 황동 덮개) — 밑이 트였다
   *   ③ 앞뒤가 트인 가운데 칸(0.44)을 양 끝에서만 막는 **평행사변형 옆판** 두 장
   *   ④ 아래 판이 위 판보다 앞으로 더 나오고 앞 모서리가 둥글다. 호두나무결 판 · 짙은 갈색 다리
   * **위 판 깊이만 사진(0.284)보다 깊게(0.34) 뒀다** — 그 위에 브라운관 TV(깊이 0.33m)가 얹힌다.
   * 사진대로 두면 TV 가 앞뒤로 2cm 씩 허공에 뜬다.
   * `surf-tv-*` 높이와 TV 의 `y` 를 이 값에 맞췄다(stage.house.ts).
   */
  TV장: () => {
    const H = 0.455, GAP = 0.48 * H, LOW_T = 0.017, TOP_T = 0.016;
    const WALNUT: RGB = [0.65, 0.68, 0.94];
    const LEG: RGB = [0.25, 0.22, 0.32];
    const BRASS: RGB = [1.30, 1.10, 0.60];
    const lowTop = GAP + LOW_T;
    return assemble([
      // 위 판 — 윗면이 0.455
      part(soft(1.0, TOP_T, 0.34, 0.3), WALNUT, [0, H - TOP_T / 2, -0.02], undefined, TILE.WOOD_C),
      // 아래 판 — 앞 모서리가 둥글고 위 판보다 앞으로 나온다
      part(soft(0.96, LOW_T, 0.393, 0.45), WALNUT, [0, GAP + LOW_T / 2, 0.01], undefined, TILE.WOOD_C),
      // ③ 평행사변형 옆판 — 위로 갈수록 뒤로 눕는다. 양 끝에서 0.06 안쪽
      ...([1, -1] as const).map((s) =>
        part(taper(new BoxGeometry(0.02, H - TOP_T - lowTop, 0.30), H - TOP_T - lowTop, 1, 0.75, -0.05), LEG,
          [s * 0.43, (lowTop + H - TOP_T) / 2, 0])),
      // ② 다리 넷 — 판 끝에서 0.147 안쪽. 아래로 가늘어지고 끝에 황동 덮개
      ...([[1, 1], [-1, 1], [1, -1], [-1, -1]] as const).flatMap(([sx, sz]) => [
        part(new CylinderGeometry(0.018, 0.012, GAP - 0.03, 8), LEG, [sx * 0.33, 0.03 + (GAP - 0.03) / 2, sz * 0.14]),
        part(new CylinderGeometry(0.012, 0.011, 0.03, 8), BRASS, [sx * 0.33, 0.015, sz * 0.14]),
      ]),
    ]);
  },

  /**
   * 책장 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/책장/` (北海道民芸家具 3단 오픈 책장, 출품 치수 90 × 29 × 103cm)
   *
   * 앞의 것은 측판 둘 · 뒷판 · 선반 셋의 나무 상자였다. 사진은 뼈대가 드러난 책장이다:
   *   ① 너비 : 높이 : 깊이 = **1 : 1.14 : 0.32** — **뒤판이 없다**
   *   ② 선반 윗면이 바닥에서 높이의 **0.085 · 0.41 · 0.71**, 그 위 가장자리가 둥근 두꺼운 천판(0.032)
   *   ③ 옆면마다 앞뒤 기둥 사이 **세로 살 7개**, 선반마다 뒤쪽에 책을 받치는 가로대
   *   ④ 기둥 밑 썰매 모양 받침 · 거의 검은 짙은 적갈색
   * 선반 높이가 바뀌어 `surf-shelf-*` 를 옮겼고, 폭이 넓어져 거실 책장을 동벽 안쪽으로 당겼다.
   */
  책장: () => {
    const W = 1, H = 1.14, D = 0.32, P = 0.035, SH = 0.023;
    const DARKWOOD: RGB = [0.20, 0.20, 0.28];   // 거의 검은 에스프레소 — 0.34 계열은 「붉은 중간 갈색」으로 떴다
    const shelves = [0.085, 0.41, 0.71].map((f) => f * H);
    return assemble([
      // 기둥 넷
      ...([[1, 1], [-1, 1], [1, -1], [-1, -1]] as const).map(([sx, sz]) =>
        part(new BoxGeometry(P, H - 0.037 - 0.04 * H, P), DARKWOOD, [sx * (W / 2 - P / 2), 0.04 * H + (H - 0.037 - 0.04 * H) / 2, sz * (D / 2 - P / 2)])),
      // ② 천판 — 좌우로 조금 나오고 가장자리를 둥글린다
      part(soft(W + 0.068, 0.037, D + 0.02, 0.4), DARKWOOD, [0, H - 0.0185, 0], undefined, TILE.WOOD_C),
      // 선반 셋 + 뒤쪽 가로대
      ...shelves.flatMap((y) => [
        part(new BoxGeometry(W - 2 * P, SH, D - 0.01), DARKWOOD, [0, y - SH / 2, 0.005], undefined, TILE.WOOD_C),
        part(new BoxGeometry(W - 2 * P, 0.03, 0.02), DARKWOOD, [0, y + 0.10, -D / 2 + 0.02]),
      ]),
      // ③ 옆면 세로 살 일곱 — 위아래 가로대 사이
      ...([1, -1] as const).flatMap((sx) => [
        part(new BoxGeometry(0.02, 0.03, D - 2 * P), DARKWOOD, [sx * (W / 2 - P / 2), H - 0.06, 0]),
        part(new BoxGeometry(0.02, 0.03, D - 2 * P), DARKWOOD, [sx * (W / 2 - P / 2), 0.07 * H, 0]),
        ...[0, 1, 2, 3, 4, 5, 6].map((k) =>
          // 살 굵기 0.009 — 간격의 1/4(사진). 굵으면 옆면이 「막힌 판」으로 읽혔다(판정자)
          part(new BoxGeometry(0.009, H - 0.13 - 0.07 * H, 0.009), DARKWOOD,
            [sx * (W / 2 - P / 2), (0.07 * H + H - 0.06) / 2, -D / 2 + P + (k + 0.5) * (D - 2 * P) / 7])),
      ]),
      // ④ 썰매 받침
      ...([1, -1] as const).map((sx) => part(soft(P + 0.01, 0.04 * H, D + 0.02, 0.3), DARKWOOD, [sx * (W / 2 - P / 2), 0.02 * H, 0])),
    ]);
  },

  /**
   * 밥상(ちゃぶ台) — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/밥상/` (쇼와 중기 둥근 접이식 ちゃぶ台, 지름 875 · 높이 295 · 천판 15mm)
   *
   * 앞의 것은 두께 0.05 상판에 둥근 다리 넷과 가로대였다. 사진과 대보니:
   *   ① 지름 : 높이 = **1 : 0.337**, 천판이 **얇다**(지름의 0.017) — 가장자리를 둥글린 테
   *   ② 천판 밑에 지름의 **0.73~0.78** 크기로 들어앉은 **네모 막판**(높이 0.06)
   *   ③ 막판 네 모서리에서 곧게 내려오는 굵기 0.045 의 **네모 다리**. 가로대는 없다
   *   ④ 노란 갈색 栓나무 불꽃결
   * `surf-table` 높이를 새 윗면(0.337 × 0.95 = 0.320)에 맞췄다. 막판 밑이 0.26 × 0.95 = 0.247 이라
   * `underPass: 0.24` 는 그대로 참이다.
   */
  밥상: () => {
    // 막판 한 변을 0.60 으로 — 사진의 0.73~0.78 은 비스듬히 본 폭이라 정사각형 한 변으로 넣으면
    // 모서리(대각 1.10)가 둥근 천판 밖으로 튀어나왔다(판정자). 다리는 천판 안쪽으로 한참 들어간다
    const H = 0.337, T = 0.017, APRON = 0.06, A = 0.60 / 2, LEG = 0.045;
    const SEN: RGB = [1.08, 1.10, 1.08];     // 연한 꿀색
    return assemble([
      part(new CylinderGeometry(0.5, 0.5, T, 28), SEN, [0, H - T / 2, 0], undefined, TILE.WOOD_F),
      part(new TorusGeometry(0.5 - T / 2, T / 2, 4, 28), [0.92, 0.95, 0.95], [0, H - T / 2, 0], [Math.PI / 2, 0, 0]),
      // ② 네모 막판 — 네 장
      ...([0, 1] as const).flatMap((k) => ([1, -1] as const).map((s) =>
        part(new BoxGeometry(k ? 0.02 : 2 * A, APRON, k ? 2 * A : 0.02), [0.88, 0.90, 0.88],
          [k ? s * (A - 0.01) : 0, H - T - APRON / 2, k ? 0 : s * (A - 0.01)]))),
      // ③ 네모 다리 넷 — 막판 모서리에서 곧게
      ...([[1, 1], [-1, 1], [1, -1], [-1, -1]] as const).map(([sx, sz]) =>
        part(new BoxGeometry(LEG, H - T - APRON * 0.3, LEG), [0.88, 0.90, 0.88],
          [sx * (A - LEG / 2), (H - T - APRON * 0.3) / 2, sz * (A - LEG / 2)], undefined, TILE.WOOD_F)),
    ]);
  },

  /**
   * 신문더미 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/신문더미/` (끈으로 묶은 폐지 신문 묶음 두 장)
   *
   * 앞의 것은 판 넷을 어긋나게 쌓고 끈 두 줄을 가로지른 것이었다. 사진과 대보니:
   *   ① 한 부 두께가 너비의 **0.026** — 층이 훨씬 촘촘하다(12 층)
   *   ② 층마다 끝이 너비의 **0.05** 까지 들쭉날쭉 삐져나온다
   *   ③ 흰 끈이 **0.55 지점을 세로로** 감고, 작은 묶음은 한 가닥 더 **십자**로 감는다
   *   ④ 층 사이 가끔 **빨간 광고면 줄**
   * 옆면 층은 인쇄(`TILE.PAPERSTACK`), 윗면은 1면 인쇄. 높이가 바뀌어 `surf-papers` 를 맞췄다.
   */
  신문더미: () => {
    const H = 12 * 0.026, D = 0.69;
    const STRING: RGB = [1.25, 1.25, 1.22];
    return assemble([
      part(new BoxGeometry(0.97, H, D - 0.02), [0.98, 0.97, 0.94], [0, H / 2, 0], undefined, TILE.PAPERSTACK),
      // ② 삐져나온 장 — 층마다 어긋나고 들뜬다. 반듯하면 「상자」로 읽혔다(판정자)
      ...([[0.03, 0.045, 0.02, 0.04], [0.08, -0.04, -0.015, -0.03], [0.13, 0.035, 0.025, 0.05], [0.18, -0.05, 0.0, -0.02],
          [0.23, 0.04, -0.02, 0.03], [0.28, -0.03, 0.015, -0.04]] as const).map(([y, dx, dz, r]) =>
        part(new BoxGeometry(0.98, 0.008, D - 0.01), [0.96, 0.97, 1.0], [dx, y, dz], [0, r, 0])),
      // 윗면 — 1면
      part(new BoxGeometry(0.975, 0.004, D - 0.015), [1.02, 1.04, 1.10], [0.01, H + 0.002, 0], undefined, TILE.NEWSPAPER),
      // ③ 끈 — 0.55 지점 세로 한 바퀴 + 긴 쪽으로 한 바퀴(십자)
      // 끈 한 가닥 — 0.55 지점을 세로로(큰 묶음 사진). 십자는 작은 묶음에서만 봤다
      part(new BoxGeometry(0.045, H + 0.012, D + 0.004), STRING, [0.05, H / 2 + 0.002, 0]),
    ]);
  },

  /**
   * 화분대 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/화분대/` (紫檀 花台, 1950년 무렵, 325 × 325 × 750mm)
   *
   * 앞의 것은 다리 셋에 둥근 판을 얹은 낮은 스탠드였다. 사진은 가늘고 높은 탑이다:
   *   ① 높이가 폭의 **2.3배**, 네 다리
   *   ② 다리는 폭의 0.05 굵기로 곧고 각지며 끝에 작은 둥근 발
   *   ③ 상판 바로 밑 높이의 0.08 띠에 **가운데가 불룩 솟은 가로대 두 줄**
   *   ④ 바닥에서 높이의 **0.14** 에 45° 돌려 끼운 **정사각형 아래 선반**
   *   ⑤ 거의 검은 적갈색 자단
   * 아래 선반이 0.14 로 내려와 `underPass` 를 그 밑(0.07 / 0.05)으로 낮췄다.
   */
  화분대: () => {
    const H = 1, W = H / 2.3, L = 0.05 * W;
    const ROSE: RGB = [0.24, 0.20, 0.27];   // 거의 검은 자단
    const legs = ([[1, 1], [-1, 1], [1, -1], [-1, -1]] as const);
    return assemble([
      part(soft(W, 0.02, W, 0.3), ROSE, [0, H - 0.01, 0], undefined, TILE.WOOD_F),
      ...legs.flatMap(([sx, sz]) => [
        part(new BoxGeometry(L, H - 0.03, L), ROSE, [sx * (W / 2 - L / 2), (H - 0.03) / 2 + 0.012, sz * (W / 2 - L / 2)]),
        part(new SphereGeometry(L * 0.6, 6, 4), ROSE, [sx * (W / 2 - L / 2), L * 0.6, sz * (W / 2 - L / 2)]),
      ]),
      // ③ 상판 밑 가로대 두 줄 — 가운데가 불룩 솟는다
      ...([0.04, 0.075] as const).flatMap((dy) => ([0, 1] as const).flatMap((k) => ([1, -1] as const).map((s) =>
        part(warp(new BoxGeometry(k ? L * 0.6 : W - 2 * L, 0.012, k ? W - 2 * L : L * 0.6, k ? 1 : 4, 1, k ? 4 : 1),
          (x, y, z) => [x, y + 0.012 * (1 - ((k ? z : x) / ((W - 2 * L) / 2)) ** 2), z]),
          ROSE, [k ? s * (W / 2 - L / 2) : 0, H - 0.02 - dy, k ? 0 : s * (W / 2 - L / 2)])))),
      // ④ 아래 선반 — 45° 돌린 정사각형과 둘레 가로대
      // 네 꼭짓점이 틀의 네 변에 닿게 — 작으면 「틀에서 떨어져 떠 있다」로 읽혔다(판정자)
      part(new BoxGeometry(W * 0.66, 0.012, W * 0.66), ROSE, [0, 0.14 * H, 0], [0, Math.PI / 4, 0], TILE.WOOD_F),
      ...([0, 1] as const).flatMap((k) => ([1, -1] as const).map((s) =>
        part(new BoxGeometry(k ? L * 0.6 : W - 2 * L, 0.015, k ? W - 2 * L : L * 0.6), ROSE,
          [k ? s * (W / 2 - L / 2) : 0, 0.13 * H, k ? 0 : s * (W / 2 - L / 2)]))),
    ]);
  },

  /**
   * 방석더미 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/방석더미/` (다다미방 구석에 쌓인 방석 14장)
   *
   * 앞의 것은 눌린 구 셋을 포갠 것이었다. 사진과 대보니:
   *   ① 방석이 **열댓 장** 쌓여 높이 ≈ 폭(1 : 1). 한 장 두께는 폭의 0.07
   *   ② **장마다 색이 다르다** — 남색 · 탁한 장밋빛 · 겨자색 · 회백색이 섞이고 줄무늬 두어 장
   *   ③ 장마다 좌우로 폭의 **0.15 까지 어긋나** 옆 윤곽이 들쭉날쭉하다
   *   ④ 각 장 앞 가장자리가 가운데는 부풀고 모서리는 눌려 층 사이에 어두운 골이 진다(`pillow`)
   * 방석 한 장의 모양은 `방석` 과 같은 `pillow()` 를 쓴다. 높이가 바뀌어 `surf-cushions` 를 맞췄다.
   */
  방석더미: () => {
    const N = 12, T = 0.085, STEP = 0.07;
    // 맨 위가 남색(사진). 배열 앞이 위다
    const COLORS: RGB[] = [
      [0.20, 0.24, 0.50], [0.55, 0.62, 0.95], [0.22, 0.26, 0.52], [1.00, 0.64, 0.68], [1.02, 0.84, 0.46],
      [0.96, 0.58, 0.60], [0.98, 0.97, 0.92], [0.93, 0.56, 0.60], [1.00, 0.82, 0.44],
      [0.20, 0.24, 0.48], [0.98, 0.60, 0.64], [0.66, 0.74, 0.84], [0.22, 0.26, 0.52],
    ];
    const OFF = [0.02, -0.04, 0.05, -0.02, 0.04, -0.05, 0.04, -0.03, 0.03, -0.04, 0.05, 0.0, -0.03, 0.03];
    /**
     * 판정자 기록(2026-09-16 트랙 D) — 「폭신한 방석이 아니라 **얇게 휜 판**이고 판 사이가 떠 있다 ·
     * 맨 위가 남색이 아니라 회색 · 술이 **커다란 금색 원뿔 가시**」.
     *   - 모서리(0.055)가 층 간격(0.068)보다 얇아 층마다 모서리에 틈이 났다 → 모서리 두께 = 층 간격 0.07,
     *     허리 오목을 0.9 → 0.95 로 줄여 판이 덜 휜다
     *   - 다다미 팔레트(19)가 남색을 회색으로 눌렀다 → 팔레트를 흰색으로, 색은 장마다 계수로
     *   - 술 — 굵기 0.018 · 길이 0.07 원뿔을 0.010 · 0.03 으로 줄이고 색을 천색으로 낮췄다
     */
    const TASSEL: RGB = [0.95, 0.82, 0.55];
    return assemble(Array.from({ length: N }, (_, i) => {
      const x = OFF[i]!, y = i * STEP, z = OFF[(i + 5) % N]! * 0.6, r = (i % 3 - 1) * 0.05;
      return [
        part(pillow(STEP, 0.078, T, 0.95, 0.006, 4).scale(0.94, 1, 0.94), COLORS[N - 1 - i]!, [x, y, z], [0, r, 0]),
        ...([1, -1] as const).map((s) =>
          part(new ConeGeometry(0.010, 0.03, 4), TASSEL, [x + s * 0.47, y + 0.03, z + 0.47], [Math.PI, 0, 0])),
      ];
    }).flat());
  },
};
