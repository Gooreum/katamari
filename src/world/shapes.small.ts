import {
  BoxGeometry, CapsuleGeometry, CircleGeometry, ConeGeometry, CylinderGeometry, ExtrudeGeometry, LatheGeometry, Shape,
  SphereGeometry, TorusGeometry, Vector2,
  type BufferGeometry,
} from 'three';
import { mergeVertices } from 'three/examples/jsm/utils/BufferGeometryUtils.js';
import type { ShapeIdSmall } from './generation';
import {
  assemble, INK, METAL, part, WHITE, WRAP, soft, warp,
  type RGB,
} from './shapes.kit';
import { TILE } from './atlas';

/** 눕힌 원기둥을 만들 때 쓰는 회전. 원기둥 축은 Y라 Z로 90° 돌리면 X축이 된다. */
const LIE_X: readonly [number, number, number] = [0, 0, Math.PI / 2];
/** X축에 눕힌 원기둥의 뚜껑을 +X 쪽 바깥으로 향하게 하는 회전 */
const CAP_X: readonly [number, number, number] = [0, 0, -Math.PI / 2];

/**
 * 침·핀의 강철. `METAL`(0.72)보다 짙다 — 압정·압핀 머리는 팔레트가 색색이라
 * 0.72 로는 대비가 0.08 밖에 안 나서 침이 머리와 한 덩어리로 뭉쳤다.
 */
const PIN: RGB = [0.42, 0.44, 0.50];

/**
 * 버킷 0~2 (1~8cm) 형태 — 원작 타케다 저택 물건.
 *
 * **작은 물체에 부품을 많이 쓰지 않는다.** 개미와 쌀알은 화면에서 몇 픽셀이고,
 * 49종을 다 채우면 이 파일의 21종이 전체 물체의 절반 가까이를 차지한다.
 * 여기서 아낀 삼각형이 고양이·서랍장의 예산이 된다.
 *
 * 치수는 **실제 크기(cm 감각)** 로 쓴다 — normalize()가 어차피 규약에 맞추므로
 * 0~1로 환산할 필요가 없고, 그러면 비율이 눈에 안 보인다.
 */
export const SMALL_BUILDERS: Record<ShapeIdSmall, () => BufferGeometry> = {
  // ─── 버킷 0 (1~2cm) ──────────────────────────────────────────

  /**
   * 개미 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/개미/` (위키미디어, 쿠로야마아리 표본 도판)
   *
   * 앞의 것은 구 셋을 늘어놓고 「가슴을 가늘게」 한 것이었다. 사진과 대보니
   * 개미의 결정적 단서는 가는 가슴이 아니라 **가슴과 배 사이의 자루마디**다 —
   * 곧추선 비늘 한 조각이 둘을 끊는다. 그 마디가 개미를 «벌레»에서 «개미»로 만든다.
   *
   * 잰 값(몸길이를 1로): 머리 0.23 · 가슴 0.32 · 자루마디 0.09 · 배 0.36.
   * 높이는 배 0.37 > 머리 0.31 > 가슴 0.26 — **배가 가장 크고 가슴이 가장 낮다.**
   * 배는 길이와 높이가 거의 같아 옆에서 보면 둥근 덩어리다.
   */
  개미: () => assemble([
    // 배 — 제일 크고 제일 둥글고 제일 높다. 길이와 높이가 거의 같다
    part(new SphereGeometry(0.185, 8, 6).scale(1.0, 0.98, 0.92), WHITE, [-0.30, 0.185, 0]),
    /**
     * 자루마디 — **곧추선 비늘 한 조각.** 가슴과 배를 끊는 이 마디가 없으면
     * 구 셋이 이어져 애벌레가 된다. 몸길이의 9%뿐이지만 여기가 전부다.
     */
    part(new BoxGeometry(0.045, 0.115, 0.055), WHITE, [-0.115, 0.175, 0]),
    /**
     * 가슴 — **등선이 두 봉우리다.** 앞가슴 봉우리와 뒷가슴 봉우리 사이가 꺼진다.
     * 매끈한 타원 하나로 두면 그 홈이 안 생겨서 개미 옆모습이 안 나온다.
     */
    part(new SphereGeometry(0.105, 8, 6).scale(1.05, 0.82, 0.86), WHITE, [0.02, 0.165, 0]),
    part(new SphereGeometry(0.082, 8, 6).scale(1.0, 0.90, 0.88), WHITE, [0.145, 0.170, 0]),
    // 머리 — 위에서 보면 폭과 길이가 거의 같은 네모꼴이다(1.04). 길쭉한 알이 아니다
    part(new SphereGeometry(0.135, 8, 6).scale(0.92, 0.98, 1.0), WHITE, [0.325, 0.170, 0]),
    /**
     * 겹눈 — 머리 길이의 32%. 머리 «옆면 위쪽»에 붙은 큰 타원이다.
     * 이 크기에서 눈이 보이는 건 색 때문이지 형태 때문이 아니다.
     */
    ...([1, -1] as const).map((k) =>
      part(new SphereGeometry(0.044, 6, 5).scale(0.7, 1.0, 1.0), INK,
        [0.345, 0.205, k * 0.105])),
    /**
     * 다리·더듬이 — 사진에서 **몸통보다 밝은 적갈색**이다. 몸통과 같은 색으로 두면
     * 검은 덩어리에 묻힌다. 여섯 다리를 따로 세우면 이 크기에서 삼각형만 먹으므로
     * 좌우 한 장씩으로 뭉치되, 색으로 몸통과 갈라 놓는다.
     */
    ...([1, -1] as const).map((k) =>
      part(new BoxGeometry(0.44, 0.030, 0.085), [1.55, 1.05, 0.72],
        [0.03, 0.095, k * 0.185])),
    /**
     * 더듬이 — **꺾인 자 모양.** 뿌리에서 곧게 뻗은 긴 마디 하나, 그 끝에서 꺾인다.
     * 곧은 막대 둘이면 벌레 아무거나이고, 꺾이면 개미다.
     */
    ...([1, -1] as const).flatMap((k) => [
      part(new CylinderGeometry(0.019, 0.015, 0.20, 5), [1.55, 1.05, 0.72],
        [0.455, 0.215, k * 0.055], [0, 0, -1.05]),
      part(new CylinderGeometry(0.015, 0.011, 0.16, 5), [1.55, 1.05, 0.72],
        [0.565, 0.285, k * 0.085], [0, 0, -0.35]),
    ]),
  ]),

  /**
   * 쌀알 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/쌀알/` (백미 한 알 접사 + 고시히카리 흩은 낟알, 치수는 스미토모화학 자료)
   *
   * 앞의 것은 원기둥 양 끝에 원뿔을 단 «알약»에 짙은 세로 홈을 그은 것이었다. 사진과 대보니:
   *   ① 길이 : 폭 : 두께 = **1 : 0.58 : 0.35** — 원기둥이 아니라 납작하고 통통한 타원 알
   *   ② 한쪽 끝 모서리를 **비스듬히 깎아낸 배아 자국** — 길이의 0.23, 폭의 0.54 깊이, 시작에 폭의 0.13 턱
   *   ③ 반대쪽 끝은 턱 없이 **둥글고 뭉툭하다**
   * 세로 홈은 사진에서 희미한 결일 뿐이라 뺐다 — 짙은 선을 그으면 알약의 쪼갬선이다.
   * 치수는 길이 = 1 로 쓴다(배아 자국 +x, +z 모서리).
   */
  쌀알: () => {
    const L = 0.5, W = 0.29, T = 0.175, CUT = 0.23;
    // 경도 16 · 위도 8 — 12 · 8 이면 깎이는 모서리에 정점이 두셋뿐이라 자국이 안 보였다(판정자 「매끈한 타원」)
    const grain = warp(new SphereGeometry(1, 16, 8).scale(L, T, W), (x, y, z) => {
      // ③ 끝을 뭉툭하게 — 길이 방향만 초타원 쪽으로 민다
      const bx = Math.sign(x) * L * Math.abs(x / L) ** 0.8;
      // ② 배아 자국 — 폭의 0.13 턱에서 시작해 끝에서 폭의 0.54 깊이까지 비스듬히 깎는다
      const x0 = L - CUT;
      if (bx > x0 && z > 0) {
        const t = (bx - x0) / CUT;
        const cap = W - 0.26 * W - t * (1.08 - 0.26) * W;
        return [bx, y, Math.min(z, cap)];
      }
      return [bx, y, z];
    });
    return assemble([part(grain, [0.97, 0.97, 0.98], [0, T, 0])]);
  },

  /**
   * 팥 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/팥/` (팥 무더기 위키미디어 + 2 mm 눈금 막대가 있는 두 알)
   *
   * 앞의 것은 타원 구 옆구리에 네모 막대를 붙인 것이었다. 사진과 대보니:
   *   ① 폭이 길이의 **0.65~0.75** 인, 양 끝이 둥글고 **옆선이 곧은 짧은 원통꼴**
   *   ② 흰 배꼽 줄은 알 길이의 **0.45~0.6**, 가운데가 아니라 **한쪽 끝으로 치우쳐** 있고 두 끝이 둥글다
   *   ③ 반들거리는 적갈색(127,81,66)과 흰 줄의 강한 대비 — 적갈 팔레트(17)에 흰색을 곱하면
   *      줄이 주황이 된다(예전 `WRAP`). 팔레트를 흰색으로 두고 껍질 색을 계수로 정한다
   * 치수는 길이 = 1 로 쓴다. 줄이 보이게 윗면에 둔다.
   */
  팥: () => {
    const R = 0.35, MID = 0.15, SQ = 0.92;
    // 알 윗면 높이 — 곧은 몸통은 평평하고 둥근 끝에서 내려간다. 줄이 이 면을 따라 휜다
    const top = (x: number): number => SQ * Math.sqrt(Math.max(0, R * R - Math.max(0, Math.abs(x) - MID) ** 2));
    // 줄은 알 곡면을 따라 휜다 — 마디가 없으면 두 끝 사이가 곧은 현이라 둥근 끝 쪽에서 알 속에 묻힌다
    // (캡슐로 만들었더니 가운데가 묻혀 양 끝 두 점만 보였다). 길이 방향으로 8 마디를 준다
    const bend = (g: BufferGeometry): BufferGeometry => warp(g.rotateZ(Math.PI / 2), (x, y, z) =>
      [x + 0.18, y * 0.55 + top(x + 0.18) - 0.012, z]);
    const hilum = bend(new CylinderGeometry(0.04, 0.04, 0.44, 5, 8));
    return assemble([
      // 몸통 — 반구 끝 원기둥을 눕히고 높이를 0.92 로 누른다
      // 껍질 — (127,81,66) 계수가 따뜻한 빛에서 연한 분홍 갈색으로 떠 「감자」로 읽혔다(트랙 D). 한 단 짙게
      part(new CapsuleGeometry(R, 2 * MID, 3, 8).scale(SQ, 1, 1), [0.40, 0.22, 0.17], [0, R * SQ, 0], LIE_X),
      // 배꼽 줄 — +x 끝에서 0.06 들어와 0.52 길이, 두 끝이 둥글게 닫힌다
      part(hilum, [1.0, 1.0, 0.93], [0, R * SQ, 0]),
      ...[-0.22, 0.22].map((x) => part(bend(new SphereGeometry(0.04, 5, 3).translate(0, x, 0)), [1.0, 1.0, 0.93], [0, R * SQ, 0])),
    ]);
  },

  /**
   * 클립 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/클립/` (위키미디어, 젬 클립)
   *
   * 앞의 것은 늘인 토러스 둘이라 화면에서 «와셔»나 «안경»이었다. 사진과 대보니
   * 클립은 고리가 아니라 **곧은 구간이 길고 곡선은 양 끝에만 있는 철사**다.
   * 늘인 토러스는 어디에도 곧은 데가 없어서 그 인상이 안 나온다.
   *
   * 잰 값: 길이 : 폭 : 철사 굵기 = **1 : 0.255 : 0.030**.
   * 안쪽 고리 길이는 전체의 0.55, 두 고리의 둥근 끝이 **서로 반대쪽**에 있다.
   * 곧은 구간을 원기둥으로, 접히는 끝만 반원 토러스로 만든다.
   */
  클립: () => assemble([
    /**
     * 바깥 고리 — 곧은 두 줄 + 왼쪽 끝의 반원. 굵기는 길이의 3%다.
     * 이 크기(3.3cm)에서 그대로 3%면 실오라기라 5%까지 올린다 —
     * 비율을 지키다 안 보이면 지킬 이유가 없다.
     */
    ...([1, -1] as const).map((k) =>
      part(new CylinderGeometry(0.048, 0.048, 0.80, 6), METAL,
        [0.06, 0.048, k * 0.115], LIE_X)),
    part(new TorusGeometry(0.115, 0.048, 5, 12, Math.PI), METAL,
      [-0.34, 0.048, 0], [Math.PI / 2, 0, Math.PI / 2]),
    /**
     * 안쪽 고리 — 전체의 0.55 길이이고 **반대쪽 끝에서 접힌다.**
     * 바깥과 같은 `METAL` 이면 두 겹이 한 덩어리로 뭉치므로 짙게 둔다.
     */
    ...([1, -1] as const).map((k) =>
      part(new CylinderGeometry(0.042, 0.042, 0.50, 6), [0.46, 0.48, 0.54],
        [0.02, 0.048, k * 0.052], LIE_X)),
    part(new TorusGeometry(0.052, 0.042, 5, 10, Math.PI), [0.46, 0.48, 0.54],
      [0.27, 0.048, 0], [Math.PI / 2, 0, -Math.PI / 2]),
  ]),

  /**
   * 압정 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/압정/` (위키미디어, 납작 원반형 「画鋲」)
   *
   * 앞의 것은 머리가 두껍고(지름의 32%) 바늘이 짧았다(지름의 72%인데 굵어서
   * 짧아 보였다). 사진과 대보니 둘 다 틀렸다:
   *   ① 머리는 **얇은 판금**이다 — 두께가 지름의 1/30 이하
   *   ② 바늘은 **원반 지름의 0.6~0.9배**로 길고, 밑동 굵기는 지름의 0.12배로 가늘다
   *   ③ 바늘 밑동에 **판을 눌러 박은 작은 턱**이 있다
   *
   * 머리를 얇게 하면 옆에서 「원반 + 바늘」이 되고, 두꺼우면 「버섯」이 된다.
   */
  압정: () => assemble([
    // 머리 — 얇은 판금. 두께를 지름의 1/28 로 둔다
    part(new CylinderGeometry(0.5, 0.5, 0.036, 20), WHITE, [0, 0.482, 0]),
    /**
     * 밑면이 **접시처럼 얕게 오목**하다. 완전한 평판이 아니다 —
     * 원뿔대를 뒤집어 밑면 쪽으로 살짝 파 넣는다.
     */
    part(new CylinderGeometry(0.47, 0.40, 0.030, 20), [0.86, 0.86, 0.88], [0, 0.449, 0]),
    // 바늘 밑동의 눌러 박은 턱 — 지름의 0.16배
    part(new CylinderGeometry(0.080, 0.055, 0.045, 10), PIN, [0, 0.414, 0]),
    // 바늘 — 원반 지름의 0.78배. 밑동 0.12배에서 끝으로 갈수록 가늘어진다
    part(new CylinderGeometry(0.060, 0.030, 0.30, 8), PIN, [0, 0.242, 0]),
    part(new ConeGeometry(0.030, 0.092, 8), PIN, [0, 0.046, 0], [Math.PI, 0, 0]),
  ]),

  단추: () => assemble([
    /**
     * 구멍 넷 + 테두리 홈. **구멍이 판 밑면까지 뚫고 나가 있었다** —
     * 원기둥 밑면이 단추 밑면과 «같은 평면»이라 z-fighting 이 넷 났다(자가 잡았다).
     * 구멍을 판 «안»에 가두고, 대신 지름을 키워 화면에서 보이게 한다.
     */
    part(new CylinderGeometry(0.5, 0.5, 0.14, 20), WHITE, [0, 0.07, 0], undefined, TILE.BUTTON),
    // 구멍 넷 — **판 «안»에 가둔다.** 밑면까지 뚫으면 단추 밑면과 같은 평면이 돼서
    // z-fighting 이 넷 난다(자가 잡았다). 파인 깊이는 인쇄가 이어서 그려 준다
    ...([[0.17, 0.17], [-0.17, 0.17], [0.17, -0.17], [-0.17, -0.17]] as const).map(
      ([x, z]) => part(new CylinderGeometry(0.095, 0.095, 0.09, 8), INK, [x, 0.075, z])),
  ]),

  /**
   * 도장 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/도장/` (위키미디어, 일본 인감 はんこ)
   *
   * 앞의 것은 길이:지름이 2.3:1 이라 뭉툭했고, 가운데를 잘록하게 파서
   * 「쥐는 것」을 만들려 했다. 사진과 대보니 둘 다 실물에 없다:
   *   ① 실물은 **길이:지름 5:1** 의 곧은 막대다. 잘록한 데가 없다
   *   ② 대신 옆면에 **위아래를 알리는 길쭉한 홈(アタリ)** 이 하나 있다.
   *      둥근 쪽 끝에서 전체 길이의 0.40 지점, 그 자리 지름의 1.3 × 0.4 크기
   *   ③ 둥근 쪽 끝은 반구가 아니라 **모서리만 굴린 평평한 끝**이다
   *
   * 잘록하게 판 것과 홈 하나는 둘 다 「쥐는 자리」를 말하지만, 실물에 있는 건 후자다.
   */
  도장: () => assemble([
    // 몸통 — 길이:지름 5:1. 세워 두므로 최장축이 세로다
    part(new CylinderGeometry(0.10, 0.10, 0.86, 12), WHITE, [0, 0.48, 0]),
    // 위쪽 끝 — 모서리만 굴린 평평한 끝. 반구를 얹으면 연필 지우개가 된다
    part(new CylinderGeometry(0.072, 0.10, 0.038, 12), WHITE, [0, 0.925, 0]),
    /**
     * 옆면의 아타리 홈 — 몸통보다 짙게. 이 홈 하나가 「손잡이 있는 막대」와
     * 「도장」을 가른다. 어느 쪽이 위인지 손으로 알려고 판 자국이다.
     */
    part(new BoxGeometry(0.040, 0.130, 0.030), [0.58, 0.50, 0.40], [0, 0.394, 0.088]),
    // 인면 — 붉은 인주가 밴 쪽. 여기가 도장의 정체다
    part(new CylinderGeometry(0.10, 0.10, 0.045, 12), [1.02, 0.36, 0.30], [0, 0.0225, 0]),
    // 인주가 끝에서 옆면으로 몇 mm 넘어와 있다 — 사진에서 본 것
    part(new CylinderGeometry(0.103, 0.103, 0.022, 12), [0.90, 0.34, 0.30], [0, 0.056, 0]),
  ]),

  // ─── 버킷 1 (2~4cm) ──────────────────────────────────────────

  주사위: () => assemble([
    // **눈을 인쇄로 새긴다.** 예전엔 원기둥 셋을 박아 윗면 1점·앞면 2점만 냈다 —
    // 나머지 네 면은 민짜였고, 그 셋이 삼각형 예산의 절반을 먹었다.
    // 아틀라스 한 칸이 여섯 면을 다 덮으면서 부품이 하나로 준다.
    part(soft(0.9, 0.9, 0.9, 0.12), WHITE, [0, 0.45, 0], undefined, TILE.DICE),
  ]),

  /**
   * 나사 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/나사/` (둥근머리 십자 목재 나사 옆모습 + 규격표)
   *
   * 앞의 것은 **머리를 위로 하고 서 있는** 기둥에 납작한 원판 머리였다. 사진과 대보니:
   *   ① 머리는 원판이 아니라 **반구 돔** — 지름이 몸통의 1.9배, 정면에 십자 홈
   *   ② 머리 밑 0.30 은 **나사산 없는 매끈한 목**, 나머지 0.70 에 나사산 11~12 개,
   *      끝 0.10 만 원뿔로 뾰족해진다
   *   ③ 바닥에 굴러다니는 나사는 **옆으로 눕는다**
   * 나사산은 부품으로 깎으면 삼각형이 폭증한다(길거리 규모에 62개) — 사선 줄 인쇄로 감는다.
   * 치수는 전체 길이 = 1 로 쓴다(머리 −x, 끝 +x).
   */
  나사: () => {
    // 머리 길이 0.18 은 반지름(0.135)보다 길어 「버섯」으로 깊었다(트랙 D) — 반구보다 조금 납작한 둥근머리로
    const R = 0.071, HEAD_R = 0.135, HEAD_L = 0.12, Y = HEAD_R;
    // 끝 원뿔을 길게(0.16) — 뭉툭하면 볼트다. 목재 나사는 끝이 송곳처럼 뾰족하다
    const x0 = -0.5 + HEAD_L, neckEnd = x0 + 0.25, threadEnd = 0.34;
    return assemble([
      // ① 돔 머리 — 반구를 머리 길이만큼 늘여 −x 로 눕힌다
      // 16면 — 10면이면 돔 가장자리가 「육각형 테두리」로 읽혀 볼트가 됐다(판정자)
      part(new SphereGeometry(HEAD_R, 16, 6, 0, Math.PI * 2, 0, Math.PI / 2).scale(1, HEAD_L / HEAD_R, 1),
        WHITE, [x0, Y, 0], [0, 0, Math.PI / 2]),
      part(new CircleGeometry(HEAD_R, 16), [0.8, 0.8, 0.8], [x0, Y, 0], [0, Math.PI / 2, 0]),
      /**
       * 십자 홈 — **돔 곡면을 따라 붙인 좁은 띠 넷.** 곧은 판 둘을 꼭지에 댔더니 판 끝이 돔 곡면
       * 밖으로 2.7mm 튀어나와 판정자가 「머리 뒤의 납작한 날개」라고 했다(2026-09-15).
       * 돔과 같은 구를 1% 크게, 경도 폭 0.34 rad · 꼭지에서 0.75 rad 까지만 잘라 네 방향에 얹는다
       */
      ...[0, 1, 2, 3].map((k) =>
        part(new SphereGeometry(HEAD_R * 1.01, 2, 4, k * Math.PI / 2 - 0.17, 0.34, 0, 0.75).scale(1, HEAD_L / HEAD_R, 1),
          INK, [x0, Y, 0], [0, 0, Math.PI / 2])),
      // ② 매끈한 목 + 나사산 + 뾰족한 끝
      part(new CylinderGeometry(R, R, neckEnd - x0, 10, 1, true), WHITE, [(x0 + neckEnd) / 2, Y, 0], [0, 0, Math.PI / 2]),
      part(new CylinderGeometry(R * 1.04, R * 1.04, threadEnd - neckEnd, 10, 1, true), WHITE,
        [(neckEnd + threadEnd) / 2, Y, 0], [0, 0, Math.PI / 2], TILE.THREAD),
      part(new ConeGeometry(R * 1.04, 0.5 - threadEnd, 10, 1, true), WHITE, [(threadEnd + 0.5) / 2, Y, 0], CAP_X, TILE.THREAD),
    ]);
  },

  /**
   * 압핀 — **사진에서 잰 값으로 다시 만들었다.** 근거: `.design-bounce/ref/압핀/` (소닉 画鋲 치수표 · 5mm 모눈)
   *
   * 앞의 것은 원기둥 손잡이 둘을 포갠 것이었다. 치수표의 체스형 압핀과 대보니:
   *   ① 손잡이가 전체 길이의 **0.55**, 바늘이 **0.45**
   *   ② 위는 좁은 납작 머리판(밑단의 0.77), 아래는 **넓게 퍼진 종 모양 치마**
   *      (지름 = 손잡이 높이의 0.75), 그 사이 기둥은 밑단의 0.44 굵기
   *   ③ 반들거리는 원색 플라스틱 한 가지와 가느다란 은색 바늘
   * 치수는 전체 길이 = 1 로 쓴다(바늘 끝이 바닥).
   */
  압핀: () => {
    const NEEDLE = 0.45, HANDLE = 0.55, SKIRT_R = 0.75 * HANDLE / 2, TOP_R = SKIRT_R * 0.77, POST_R = SKIRT_R * 0.44;
    return assemble([
      // ③ 바늘 — 끝이 뾰족하다
      part(new ConeGeometry(0.018, NEEDLE * 0.25, 6), PIN, [0, NEEDLE * 0.125, 0], [Math.PI, 0, 0]),
      part(new CylinderGeometry(0.018, 0.018, NEEDLE * 0.75, 6), PIN, [0, NEEDLE * 0.25 + NEEDLE * 0.375, 0]),
      // ② 종 모양 치마 — 아래가 넓다
      part(new CylinderGeometry(POST_R * 1.1, SKIRT_R, HANDLE * 0.25, 16), WHITE, [0, NEEDLE + HANDLE * 0.125, 0]),
      // 기둥
      part(new CylinderGeometry(POST_R * 0.92, POST_R, HANDLE * 0.55, 12), WHITE, [0, NEEDLE + HANDLE * 0.25 + HANDLE * 0.275, 0]),
      // 납작 머리판
      part(new CylinderGeometry(TOP_R, TOP_R, HANDLE * 0.12, 16), WHITE, [0, NEEDLE + HANDLE * 0.8 + HANDLE * 0.06, 0]),
      part(new SphereGeometry(TOP_R, 16, 4, 0, Math.PI * 2, 0, Math.PI / 2).scale(1, 0.25, 1), WHITE, [0, NEEDLE + HANDLE * 0.92, 0]),
    ]);
  },


  /**
   * 지우개 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/지우개/` (톰보 MONO 플라스틱 지우개)
   *
   * 앞의 것은 길이 : 폭 : 두께 = 1 : 0.47 : 0.38 의 두툼한 덩어리에 옆으로 비낀 조각이 붙어 있었다.
   *   ① 길이 : 폭 : 두께 = **1 : 0.39 : 0.2** — 납작하다
   *   ② 한쪽 끝 **0.18 만 드러난 크림빛 고무**, 나머지 0.82 를 슬리브가 감싼다
   *   ③ 슬리브의 가로 3단 띠 — 파랑 0.38 · 크림 0.19 · 검정 0.43 (인쇄)
   */
  지우개: () => assemble([
    part(soft(1.0, 0.20, 0.39, 0.18), [1.0, 0.98, 0.90], [0, 0.10, 0]),
    // 슬리브 — 고무보다 아주 조금 크게 감싼다. 한쪽 끝(−x) 0.18 을 남긴다
    // 슬리브 — 몸통은 무늬 없이, 3단 띠는 윗면 한 장에만. 모든 면에 감으면 옆면 띠가 뒤집혀 보였다(판정자).
    // 긴 옆면은 띠가 넘어가는 색 — 앞(+z)은 검정, 뒤(−z)는 파랑
    part(soft(0.82, 0.206, 0.396, 0.08), [0.95, 0.93, 0.85], [0.09, 0.10, 0]),
    part(new BoxGeometry(0.80, 0.003, 0.39), WHITE, [0.09, 0.2045, 0], undefined, TILE.ERASER),
    part(new BoxGeometry(0.80, 0.19, 0.003), [0.12, 0.12, 0.12], [0.09, 0.10, 0.1995]),
    part(new BoxGeometry(0.80, 0.19, 0.003), [0.20, 0.32, 0.72], [0.09, 0.10, -0.1995]),
  ]),

  각설탕: () => assemble([
    /**
     * **각설탕은 각져야 한다.** 예전 모따기 0.16 은 짧은 변(0.80)의 16% —
     * 12.8mm 를 깎은 셈이라 화면에서 «둥근 가방»이었다. 6% 로 낮춘다.
     * 그리고 윗면의 혹 둘이 몸통과 같은 `WHITE` 라 표식이 아니었다 —
     * 설탕은 «눌러 굳힌 알갱이»니 결을 인쇄로 넣고 모서리 하나만 깬다.
     */
    /**
     * **부품 하나로 끝낸다.** 「부스러진 모서리」로 구를 둘 붙여 봤는데 화면에서
     * 각설탕에 «공이 박힌» 걸로 보였다 — 각진 것에 둥근 것을 붙이면 그게 먼저 읽힌다.
     * 알갱이 결은 인쇄가 낸다(길 C).
     */
    part(soft(0.88, 0.80, 0.86, 0.030), WHITE, [0, 0.40, 0], undefined, TILE.SUGAR),
    /**
     * **꼭짓점을 뭉갠다.** 사진에서 「온전한 꼭짓점을 가진 덩어리가 한 개도 없었다」.
     * 모서리 «선»은 곧게 살아 있는데 꼭짓점만 조금씩 떨어져 나간다 —
     * 모따기를 키우면 선까지 같이 둥글어져 「둥근 가방」이 되므로(예전 실패),
     * 모따기는 3%로 더 낮추고 **꼭짓점 넷에만** 작은 판을 깎아 앉힌다.
     */
    ...([[1, 1], [-1, -1], [1, -1], [-1, 1]] as const).map(([sx, sz]) =>
      part(new BoxGeometry(0.13, 0.13, 0.13).rotateY(0.62).rotateX(0.55), WHITE,
        [sx * 0.40, sz > 0 ? 0.775 : 0.025, sz * 0.39], undefined, TILE.SUGAR)),
  ]),

  사탕: () => assemble([
    /**
     * 알맹이 + 양쪽으로 «꼬인» 포장지. 예전엔 포장이 `PAPER`(대비 0.04)라
     * 알맹이와 한 덩어리였고, 6분할 원뿔이라 각진 혹으로 보였다.
     * `WRAP` 으로 밝게 갈라내고 꼬임 마디를 하나씩 넣는다.
     */
    part(new SphereGeometry(0.32, 12, 8).scale(1, 0.92, 0.92), WHITE, [0, 0.32, 0]),
    ...([1, -1] as const).flatMap((k) => [
      part(new ConeGeometry(0.30, 0.26, 10), WRAP, [k * 0.32, 0.32, 0],
        k > 0 ? CAP_X : LIE_X),
      // 꼬임 마디 — 이게 있어야 「비틀어 싼」 것이 된다
      part(new CylinderGeometry(0.075, 0.11, 0.10, 8), WRAP, [k * 0.50, 0.32, 0],
        k > 0 ? CAP_X : LIE_X),
      part(new ConeGeometry(0.13, 0.16, 8), WRAP, [k * 0.62, 0.32, 0],
        k > 0 ? CAP_X : LIE_X),
    ]),
  ]),

  /**
   * 성냥 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/성냥/` (위키미디어 + 머리 접사)
   *
   * 앞의 것은 머리를 «넉넉히 키운» 구였다. 사진에서 재니 머리는
   * **축보다 1.10배만 굵다** — 구슬이 아니라 축 끝을 감싸고 총알처럼 맺힌다.
   * 크게 키우면 성냥이 아니라 성냥«팔이»가 된다.
   *
   * 잰 값: 전체 길이 : 굵기 = 1 : 0.052 · 머리 길이는 전체의 9.4%.
   * 축은 원기둥이 아니라 **모서리가 선 각기둥**이다(개비마다 평평한 옆면이 보인다).
   */
  성냥: () => assemble([
    // 축 — 각기둥. 모따기를 거의 안 줘야 옆면이 평평하게 선다
    part(soft(0.94, 0.052, 0.052, 0.10), WHITE, [0, 0.026, 0]),
    /**
     * 머리 — 축보다 1.10배만 굵고, 총알 끝처럼 맺힌다.
     * 구를 얹으면 「막대 끝의 구슬」이지 성냥 머리가 아니다.
     */
    part(new CylinderGeometry(0.0286, 0.0286, 0.062, 6), [0.86, 0.26, 0.20],
      [0.437, 0.026, 0], LIE_X),
    part(new SphereGeometry(0.0286, 6, 5).scale(1.25, 1, 1), [0.86, 0.26, 0.20],
      [0.468, 0.026, 0]),
    /**
     * 머리와 나무의 경계 — 사진에서 **한 줄로 딱 끊기지 않고 비스듬히 어긋난다.**
     * 짧은 띠 하나를 중간 톤으로 겹쳐 그 얼룩진 경계를 만든다.
     */
    part(new CylinderGeometry(0.0270, 0.0270, 0.020, 6), [0.90, 0.62, 0.46],
      [0.399, 0.026, 0], LIE_X),
  ]),

  // ─── 버킷 2 (4~8cm) ──────────────────────────────────────────

  /**
   * 크레용 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/크레용/` (사쿠라 Hi CRAY-PAS 50색)
   *
   * 앞의 것은 **끝이 원뿔로 뾰족하게 깎인** 연필꼴이었다. 사진과 대보니:
   *   ① 길이 : 지름 = **1 : 0.163** 의 곧은 원기둥 — 끝은 뾰족하지 않고 **뭉툭하게 잘렸다**
   *   ② 몸통 0.67 을 크라프트 종이가 감싸고, 끝에서 0.03 떨어져 **0.19 폭 올리브 띠**가 두른다
   *   ③ 반대쪽 끝 **0.11 만** 크레파스 색이 드러난다
   * 크레파스 색은 팔레트가 정한다(여섯 색). 종이는 팔레트 색에 곱해져 옅은 같은 계열로 나온다 —
   * 팔레트에 무관한 크라프트색은 곱하기로는 못 만든다.
   * 치수는 길이 = 1 로 쓴다(드러난 끝이 +x).
   */
  크레용: () => {
    const R = 0.0815, Y = R;
    return assemble([
      // ③ 드러난 크레파스 — +x 끝 0.11. 모서리만 살짝 닳았다
      part(new CylinderGeometry(R * 0.96, R * 0.96, 0.11, 12), WHITE, [0.445, Y, 0], LIE_X),
      // ① 종이 — 0.67
      part(new CylinderGeometry(R, R, 0.67, 12, 1, true), [1.55, 1.45, 1.30], [0.055, Y, 0], LIE_X, TILE.PAPER),
      // ② 올리브 띠 — 0.19, −x 끝에서 0.03 떨어진다
      part(new CylinderGeometry(R * 1.01, R * 1.01, 0.19, 12, 1, true), [0.78, 0.74, 0.40], [-0.375, Y, 0], LIE_X),
      // −x 끝 0.03 드러난 크레파스 + 마구리
      part(new CylinderGeometry(R * 0.96, R * 0.96, 0.03, 12), WHITE, [-0.485, Y, 0], LIE_X),
    ]);
  },

  /**
   * 캐러멜 (4.4cm) — **실물 사진을 보고 다시 만들었다.**
   * 근거: `.design-bounce/ref/캐러멜/` (위키미디어, 자가 함께 찍힌 사진)
   *
   * 앞의 것은 「각진 직육면체에 종이 띠를 두르고 양끝을 접은 것」이었다.
   * 문장으로는 맞게 읽히는데 실물이 아니었다. 사진을 보니 셋이 달랐다:
   *
   *   ① **거의 정육면체다.** 잰 값 1 : 0.85 : 0.72. 앞의 것은 1 : 0.55 : 0.64 —
   *      납작한 막대였다
   *   ② **모서리가 크게 뭉개졌고 옆구리가 눌려 오목하다.** 모따기 0.10 은 너무 각지다
   *   ③ **포장을 벗은 갈색 덩어리다.** 종이 띠와 양옆 날개를 붙이면 캐러멜이 아니라
   *      그냥 「포장된 사탕」으로 읽힌다 — 판정자가 실제로 「사탕」이라고 답했다
   *
   * 팔레트도 노랑(10)에서 적갈(17)로 옮겼다. 캐러멜은 갈색이다.
   */
  캐러멜: () => assemble([
    /**
     * 몸통 — 사진에서 잰 1 : 0.85 : 0.72.
     *
     * **갑의 포장지 인쇄(`TILE.CARAMEL`)를 붙이지 않는다.** 벗긴 알맹이에 감으면
     * 종이가 붙은 것으로 읽힌다 — 판정자가 실제로 「갈색 덩어리를 얇은 판 두 장이
     * 감싸고 있다」고 적었다. 대신 눌린 자국만 있는 `TILE.TOFFEE` 를 쓴다.
     *
     * **모따기는 0.42 → 0.24.** 처음에 최대에 가깝게 줬더니 면이 하나도 안 남아
     * «돌멩이»가 됐다. 실물은 판을 잘라 만든 것이라 면이 살아 있고 모서리만 둥글다.
     *
     * **색은 팔레트가 아니라 계수로 잡는다.** 적갈(0x8a4f2a)은 초콜릿이라 너무 짙고,
     * 살구(0xdca87a)로 옮겼더니 이번엔 **바닥과 같은 색**이 됐다 —
     * 판정자가 「경계가 그림자로만 겨우 구분된다」고 적었다. 다다미·마루가 전부
     * 밝은 황갈색인 이 게임에서 밝은 황갈색 물건은 바닥에 묻힌다.
     * 적갈에 1.38 을 곱하면 (190, 104, 52) — 캐러멜 색이면서 바닥에서 떠오른다.
     *
     * **눕혀 놓는다.** 사진의 캐러멜은 서 있지 않고 «누워» 있다 —
     * 가로:높이:깊이 = 1 : 0.62 : 0.78. 앞의 0.82 는 너무 높아서 정육면체에
     * 가까웠고, 그래서 「상자」로 읽혔다. 실물은 판을 자른 조각이라 낮고 넓다.
     */
    /**
     * **모따기를 걷어냈다 (0.26 → 0.09).** 「지점토 같다」는 지적을 받았고
     * 원인이 이것이다 — 모든 모서리를 고르게 둥글리면 «주물러 만든 것»이 된다.
     *
     * 실물 캐러멜은 **판을 칼로 자른 조각**이다. 면이 평평하고 모서리가 살아 있으며
     * 아주 살짝만 무디다. 둥근 게 아니라 **각진 게** 캐러멜이다.
     */
    /**
     * **부품 하나뿐이다. 더할수록 나빠졌다.**
     *
     * 이 형상에 여섯 번 손댔고, 더한 것은 전부 다른 물건을 만들었다:
     *   자른 면 판 둘 → 「포장지 두 장」 · 허리 띠 → 「소파」 ·
     *   부푼 판 → 「방석」 · 얼룩 네모 → 「골판지 상자」 ·
     *   속에 넣은 타원체 → 윗면 둘레에 «뚜껑 테두리» 선
     *
     * 마지막 것이 특히 그렇다. 면 가운데를 밀어 「무른 것」을 만들려 했는데,
     * 타원체가 모서리 쪽에서 다시 안으로 들어가면서 **둘레에 주름 한 줄**이 생겼다.
     * 판정자가 그걸 뚜껑 테두리로 읽었다 — 없애려던 상자를 오히려 만든 것이다.
     *
     * 4.4cm 짜리에 얹을 자리는 없다. 남은 건 **비율·색·모따기 셋**뿐이다.
     */
    part(soft(0.64, 0.40, 0.50, 0.17), [1.38, 1.32, 1.24], [0, 0.20, 0], undefined, TILE.TOFFEE),
  ]),
  /**
   * **부품을 둘 더 붙였다가 둘 다 뺐다.** 눌린 자국을 기하로 만들려고
   *   ① 위아래 「자른 면」 판 둘 → 몸통 밖으로 비어져 나와 «포장지 두 장»으로 읽혔다
   *   ② 허리에 짙은 띠 하나  → 턱이 생겨 판정자가 «소파»라고 답했다
   *      (「넓고 각진 등받이 면, 앞쪽 아래 낮은 턱, 왼쪽 끝 팔걸이」)
   *
   * **흔적을 부품으로 만들면 흔적이 아니라 부속이 된다.** 눌린 자국은
   * 인쇄(`TILE.TOFFEE`)로 넣는다 — 삼각형도 0 늘고 실루엣도 안 망가진다.
   */

  /**
   * 체온계 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/체온계/` (옛 수은 체온계 박물관 사진 + 일본 체온계 · 색 참고)
   *
   * 앞의 것은 유리 막대 끝에 **굵은 붉은 구슬**과 붉은 줄을 얹은 것이었다. 사진과 대보니:
   *   ① 길이 : 지름 = **1 : 0.068** 의 가느다란 유리 막대, 두 끝이 둥글게 막혔다
   *   ② 수은 구는 굵은 구슬이 아니라 **관보다 가는(0.41) 은빛 막대** — 길이의 0.16, 나팔꼴 목으로 관에 이어진다
   *   ③ 길이의 **0.26 ~ 0.88** 구간에 흰 눈금판 — 위쪽 절반 노란 띠, 아래쪽 숫자, 37 만 빨강(`TILE.THERMO`)
   * 유리는 불투명이라 속 눈금판을 관 윗면에 붙여 보인다. 치수는 길이 = 1 로 쓴다(수은 구 −x).
   */
  체온계: () => {
    const R = 0.034, BULB = 0.16, NECK = 0.09, GLASSY: RGB = [0.80, 0.88, 0.92];
    const x0 = -0.5, xNeck = x0 + BULB, xTube = xNeck + NECK, xEnd = 0.5 - R;
    return assemble([
      // ② 수은 구 — 관보다 가는 은빛 막대(끝이 둥글다)
      part(new CapsuleGeometry(R * 0.41, BULB - R * 0.82, 2, 8), [0.42, 0.43, 0.46], [x0 + BULB / 2, R, 0], LIE_X),
      // 나팔꼴 목 — 위(+y → +x)가 관 쪽으로 벌어진다
      part(new CylinderGeometry(R, R * 0.47, NECK, 10), GLASSY, [xNeck + NECK / 2, R, 0], CAP_X),
      // ① 유리 관 + 둥글게 막힌 끝
      part(new CylinderGeometry(R, R, xEnd - xTube, 10, 1, true), GLASSY, [(xTube + xEnd) / 2, R, 0], CAP_X),
      part(new SphereGeometry(R, 10, 5, 0, Math.PI * 2, 0, Math.PI / 2), GLASSY, [xEnd, R, 0], CAP_X),
      // ③ 눈금판 — 0.26 ~ 0.88
      // 눈금판 — 관 폭을 거의 다 채운다(트랙 D 「사진은 폭을 거의 채운다」)
      part(new BoxGeometry(0.62, 0.003, R * 1.8), WHITE, [-0.5 + 0.26 + 0.31, R * 2 - 0.004, 0], undefined, TILE.THERMO),
    ]);
  },

  /**
   * 간장 팩(물고기 모양 간장병) — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/간장 팩/` (旭創業 제품 옆모습, 표기 54 × 23 mm)
   *
   * 앞의 것은 구 + 원뿔 + 짧은 원기둥 뚜껑이었다. 사진과 대보니:
   *   ① 길이 : 높이 = **1 : 0.42**. 몸통은 병 길이의 **0.61** 인 앞뒤 거의 대칭 레몬꼴
   *      (한가운데가 가장 높다) — 구를 늘인 달걀꼴이 아니다
   *   ② 빨간 뚜껑은 **몸 쪽이 넓은 원뿔대**, 길이 0.19 · 몸 쪽 지름이 몸통 높이의 0.40
   *   ③ 간장이 차서 **거의 검은 몸통**(35,35,41)과 간장이 안 드는 **우윳빛 꼬리**(길이 0.15,
   *      자루 0.26 → 끝 0.56 높이로 벌어진다)의 대비. 등지느러미 속 간장은 호박색으로 비친다
   * 적갈 팔레트(17)에 곱하면 검은 몸통 · 흰 꼬리 · 빨간 뚜껑이 한 색으로 뭉친다 — 팔레트는 흰색.
   * 치수는 길이 = 1 로 쓴다(뚜껑 +x, 꼬리 −x).
   */
  '간장 팩': () => {
    // 몸통은 간장 빛 — 가운데 거의 검고 가장자리가 적갈(69,49,50). 회색으로 뜨지 않게 붉은 기를 준다
    const RM = 0.18, BODY = 0.61, FLAT = 0.55, SOY: RGB = [0.17, 0.11, 0.11];
    // ① 몸통 옆 윤곽 — [최대 높이에 대한 비, 꼬리 쪽 끝에서의 거리]. 사진 x=300·350·415·500·540 에서 잰 값
    // 꼬리 — 자루(높이 0.26 × RM × 2) 에서 끝(0.56)으로 벌어지고 끝선이 살짝 오목하다. 두께 0.02
    const fin = new Shape();
    fin.moveTo(0, -0.052); fin.lineTo(-0.15, -0.112); fin.lineTo(-0.145, 0); fin.lineTo(-0.15, 0.112); fin.lineTo(0, 0.052);
    const tail = mergeVertices(new ExtrudeGeometry(fin, { depth: 0.02, bevelEnabled: false }).deleteAttribute('uv').deleteAttribute('normal')).translate(0, 0, -0.01);
    tail.computeVertexNormals();
    const prof = [[0.001, 0], [0.26, 0], [0.55, 0.043], [0.74, 0.128], [1.0, 0.311], [0.86, 0.451], [0.61, 0.561], [0.33, BODY], [0.001, BODY]]
      .map(([k, y]) => new Vector2(k! * RM, y!));
    return assemble([
      // 돌림축을 +x 로 눕히고(Z −90°) 두께만 0.55 로 누른다 — 옆으로 납작한 물고기
      part(new LatheGeometry(prof, 12).scale(1, 1, FLAT), SOY, [-0.35, RM, 0], CAP_X),
      // 목 — 몸통과 뚜껑 사이 0.05
      part(new CylinderGeometry(0.062, 0.062, 0.05, 10), SOY, [0.285, RM, 0], CAP_X),
      // ② 뚜껑 — 원기둥 위(+y → +x)가 바깥 끝. 몸 쪽이 넓다
      // 게임의 따뜻한 빛에서 (190,74,70) 은 분홍으로 떴다(판정자 「분홍 원통」) — 채도를 올린다
      part(new CylinderGeometry(0.054, 0.080, 0.19, 12), [0.82, 0.20, 0.18], [0.405, RM, 0], CAP_X),
      // ③ 꼬리 — 사다리꼴 «판». 네모 원뿔대를 눌렀더니 위아래가 뾰족해 「흰 원뿔 · 깔때기」로 읽혔다(트랙 D)
      part(tail, [0.90, 0.90, 0.88], [-0.35, RM, 0]),
      // 등지느러미 — 간장이 얇게 비치는 호박색
      part(new SphereGeometry(0.06, 8, 4).scale(1.5, 0.6, 0.35), [0.61, 0.44, 0.22], [-0.04, RM * 2 - 0.004, 0]),
      // 눈 — 머리 쪽 윗편, 양옆
      ...([1, -1] as const).map((k) =>
        part(new SphereGeometry(0.02, 6, 4), [0.55, 0.53, 0.57], [0.20, RM + 0.03, k * 0.056])),
    ]);
  },

  /**
   * 청개구리(ニホンアマガエル) — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/청개구리/` (옆모습 · 위 · 옆 2)
   *
   * 앞의 것은 둥근 몸 · 머리 구 위에 눈두덩 둘 · 짙은 입선이었다. 사진과 대보니:
   *   ① 몸길이 : 높이 ≈ **1 : 0.5** 의 웅크린 물방울꼴 — 등선이 **눈 뒤 머리 둔덕(가장 높은 점, 0.58)** 에서
   *      엉덩이로 **곧게** 내려간다. 둥근 공 둘이 아니다
   *   ② 주둥이 끝에서 0.11 뒤, 몸길이 **0.09** 크기로 옆으로 튀어나온 까만 눈
   *   ③ 콧구멍 → 눈 → **고막(눈의 0.7 갈색 동그라미)** 으로 이어져 초록 등과 **베이지 배**를 가르는 갈색 줄
   *   ④ 몸 옆에 꼭 붙여 접은 뒷다리 허벅지(몸길이의 0.29)와 황갈색 발가락
   * 입선은 사진에 없다 — 뺐다. 배 · 줄 · 발은 연두 팔레트(12)에 곱해 사진 색이 나오게 계수를 잡았다.
   * 치수는 몸길이 = 1 로 쓴다(주둥이 +x).
   */
  청개구리: () => {
    const BEIGE: RGB = [1.28, 0.70, 1.88], BROWN: RGB = [0.94, 0.47, 0.40], TAN: RGB = [1.35, 0.72, 1.78];
    // ① 몸통 — 윗면만 앞으로 갈수록 높게 민다(엉덩이 0.36 → 머리 둔덕 0.58)
    const body = warp(new SphereGeometry(1, 10, 7).scale(0.42, 0.20, 0.27), (x, y, z) =>
      [x, y > 0 ? y * (1 + 0.9 * Math.max(0, (x + 0.42) / 0.84)) : y, z]);
    return assemble([
      part(body, WHITE, [-0.06, 0.20, 0]),
      // 머리 — 몸통 앞끝에서 이어져 주둥이로 모인다
      part(new SphereGeometry(0.17, 8, 6).scale(1.0, 0.85, 1.0), WHITE, [0.30, 0.30, 0]),
      // ③ 베이지 배 — 몸통 아래 절반
      // 배는 몸통보다 조금 넓게 — 안에 묻혀 온몸이 초록으로 보였다(트랙 D)
      part(new SphereGeometry(1, 8, 3, 0, Math.PI * 2, Math.PI / 2, Math.PI / 2).scale(0.42, 0.14, 0.29), BEIGE, [0.02, 0.14, 0]),
      ...([1, -1] as const).flatMap((k) => [
        // ② 눈 — 초록 눈두덩 위로 까만 눈이 옆을 본다
        part(new SphereGeometry(0.065, 6, 4), WHITE, [0.37, 0.40, k * 0.12]),
        part(new SphereGeometry(0.045, 6, 4), [0.25, 0.18, 0.60], [0.39, 0.41, k * 0.165]),
        // ③ 갈색 줄(콧구멍 → 눈 아래 → 고막) + 고막
        // 줄 — 머리 밖으로 막대처럼 튀어나왔다(트랙 D). 짧게, 머리 면에 붙인다
        part(new SphereGeometry(1, 4, 3).scale(0.08, 0.014, 0.015), BROWN, [0.36, 0.345, k * 0.150], [0, 0, 0.30]),
        part(new SphereGeometry(0.03, 4, 3).scale(1, 1, 0.5), BROWN, [0.24, 0.32, k * 0.19]),
        // ④ 접은 허벅지 + 발가락
        part(new SphereGeometry(1, 6, 4).scale(0.15, 0.10, 0.085), WHITE, [-0.28, 0.12, k * 0.24]),
        // 발 — 허벅지 끝에 붙인다(따로 떨어진 판으로 읽혔다). 앞다리를 세운다
        part(new SphereGeometry(1, 4, 3).scale(0.13, 0.025, 0.06), TAN, [-0.14, 0.03, k * 0.28], [0, k * 0.5, 0]),
        part(new CylinderGeometry(0.025, 0.03, 0.12, 5), TAN, [0.22, 0.07, k * 0.19], [k * 0.3, 0, 0]),
        part(new SphereGeometry(1, 4, 3).scale(0.06, 0.02, 0.05), TAN, [0.25, 0.015, k * 0.22]),
      ]),
    ]);
  },

  성냥갑: () => assemble([
    /**
     * 서랍이 살짝 빠진 갑. **빠진 서랍이 `PAPER`(대비 0.04)라 갑과 한 덩어리였다** —
     * 「빠진 단이 있어야 성냥갑」이라고 적어놓고 실제로는 안 보이고 있었다.
     * `WRAP` 으로 갈라내고, 서랍 안에 성냥 머리가 보이게 한다.
     */
    // 잰 값: 라벨 가로:세로 = 1.55 : 1. 앞의 0.86 : 0.56 = 1.54 : 1 로 이미 맞았다
    part(soft(0.87, 0.235, 0.562, 0.10), WHITE, [0, 0.118, 0], undefined, TILE.MATCHBOX),
    part(soft(0.36, 0.19, 0.50, 0.10), WRAP, [0.53, 0.115, 0]),
    // 빠진 서랍 안의 성냥 머리 — 「안에 뭐가 들었다」가 보여야 갑이다
    // 서랍 «안»에 가둔다 — 윗면이 서랍 윗면과 같은 평면이면 z-fighting 이다
    part(new BoxGeometry(0.26, 0.05, 0.42), [0.86, 0.30, 0.24], [0.55, 0.172, 0]),
    // 옆면 마찰지
    part(new BoxGeometry(0.86, 0.17, 0.025), INK, [0, 0.12, 0.285]),
  ]),

  /**
   * 건전지 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/건전지/` (위키미디어, AA 건전지)
   *
   * 잰 값: 길이 : 지름 = 1 : 0.276 (내 것은 1 : 0.65 — **두 배 넘게 뚱뚱했다**).
   * 양극 돌기는 몸통 지름의 0.37 굵기에 전체 길이의 0.024 높이 —
   * 아주 «납작한» 단추다. 내 것은 높이가 0.116 이라 뾰족한 꼭지였다.
   *
   * 몸통이 뚱뚱하면 건전지가 아니라 통조림이 된다.
   */
  건전지: () => assemble([
    part(new CylinderGeometry(0.138, 0.138, 0.94, 16), WHITE, [0, 0.50, 0],
      undefined, TILE.BATTERY),
    /**
     * 양극 돌기 — 몸통 지름의 0.37, 높이는 전체의 0.024. **납작해야 한다.**
     * 끝에 밝은 크롬 링이 비스듬히 꺾여 올라간다(전체 길이의 1.5%).
     */
    part(new CylinderGeometry(0.051, 0.051, 0.023, 10), WRAP, [0, 0.982, 0]),
    part(new CylinderGeometry(0.125, 0.138, 0.014, 16), [0.62, 0.64, 0.68], [0, 0.964, 0]),
    // 음극 — 평평한 바닥. 위와 달리 돌기가 없다
    part(new CylinderGeometry(0.138, 0.138, 0.016, 16), [0.52, 0.54, 0.58], [0, 0.038, 0]),
  ]),

  화투: () => assemble([
    // 흩어진 낱장 석 장 (5.5cm). **겹쳐야 카드로 읽힌다** — 한 장이면 그냥 얇은 판이다.
    // 원작 거실 바닥에 이렇게 흩어져 있고, 공에 붙으면 납작한 면이 밖으로 선다.
    // 잰 값: 가로:세로 = 1 : 1.60, 두께는 가로의 0.025. 앞의 1:1.55·0.048 보다 얇고 길다
    ...([[0.0, 0.014, 0.0, 0.0], [0.10, 0.043, 0.06, 0.32],
         [-0.08, 0.072, -0.05, -0.18]] as const).map(([x, y, z, r]) =>
      part(new BoxGeometry(0.60, 0.015, 0.96), WHITE, [x, y, z], [0, r, 0], TILE.CARD)),
  ]),
};
