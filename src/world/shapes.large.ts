import {
  BoxGeometry, CircleGeometry, ConeGeometry, CylinderGeometry, SphereGeometry, TorusGeometry,
  type BufferGeometry,
} from 'three';
import type { ShapeIdLarge } from './generation';
import { assemble, INK, invert, part, SEG, WHITE, WRAP, soft, warp,
  type RGB,
} from './shapes.kit';
import { TILE } from './atlas';

const LIE_Z: readonly [number, number, number] = [Math.PI / 2, 0, 0];

/**
 * 버킷 6 (60cm~1.2m) 형태 — 원작 타케다 저택의 가구·동물.
 *
 * **집 맵에서 제일 큰 것들이다.** 예전 이 파일에는 승용차·전봇대 같은
 * 2.5~5m 물건이 있었는데, 그건 동네 맵의 크기다. 집 안에서 제일 큰 건
 * 서랍장·텔레비전이고 그게 1m 남짓이다.
 *
 * 7종뿐이라 종당 부품을 넉넉히 쓴다 — 이 크기에서는 실루엣만으로 안 되고
 * 다리·서랍·손잡이가 보여야 가구로 읽힌다.
 */
/**
 * **고양이만 면 수를 한 단 낮춘다.** 거리 장면에 고양이가 170마리라 한 마리 2080 삼각형이
 * 씬 예산(200만)의 18% 를 먹었다(2026-09-16, 여유 3%). 몸통 20 → 16, 머리·다리 14 → 11,
 * 작은 부품 10 → 8. 모양을 정하는 비율 · 위치는 한 글자도 안 바꿨다.
 */
const CAT_SEG = { BIG: 16, MID: 11, SMALL: 8 } as const;

export const LARGE_BUILDERS: Record<ShapeIdLarge, () => BufferGeometry> = {
  /**
   * 고양이 — **앉은 자세로 다시 세웠다.**
   * 근거: `.design-bounce/ref/고양이/` (위키미디어)
   *
   * 앞의 것은 웅크린 자세였는데, 사진에서 잰 것과 두 군데가 어긋났다:
   *   ① **앞다리가 곧게 선다.** 앉은 고양이의 실루엣은 «세로»다 — 가슴에서
   *      앞발까지 한 줄로 내려온다. 웅크리면 몸통이 큰 공이 되고,
   *      판정자가 실제로 「큰 공 모양 몸통」이라고 적었다
   *   ② **머리가 전체 높이의 28%.** 앞의 것은 몸통이 커서 머리가 묻혔다
   *
   * `normalize()` 가 최장축을 1.0 으로 맞추므로 세로로 세우면 «키»가 최장축이 된다.
   * 크기(`size`)·충돌 상자는 그대로다.
   */
  /**
   * 고양이 — **한 덩어리로 다시 만들었다.**
   * 근거: `.design-bounce/ref/고양이/` (위키미디어)
   *
   * 「형이상학적이다」는 지적을 받았고 원인은 만드는 방식이었다.
   * 앞의 것은 **엉덩이 구 + 허벅지 둘 + 몸통 원뿔대 + 어깨 구 + 목 원기둥 + 머리 구**
   * 를 «쌓았다». 부품마다 경계가 보여서 고양이가 아니라 **눈사람**이 됐다.
   * 살아 있는 것은 부품의 합이 아니라 «한 겹의 표면»이다.
   *
   * 그래서 규칙을 바꿨다:
   *   ① 덩어리를 **크게, 적게, 많이 겹친다.** 이웃과 절반쯤 파묻히면 경계가 사라진다
   *   ② **목을 없앤다.** 앉은 고양이는 머리가 어깨에 «박혀» 있다.
   *      원기둥을 끼우면 그 자리에 반드시 테가 생긴다(실제로 생겼다)
   *   ③ 귀는 **납작하다.** 정원뿔은 뿔이지 귀가 아니다 — z 를 눌러 판으로 만든다
   */
  고양이: () => assemble([
    /**
     * 몸통 하나 — 아래가 무겁고 위가 좁은 «달걀». 이것 하나가 앉은 자세의
     * 실루엣 대부분을 만든다. 부품을 늘리는 대신 이걸 키웠다.
     */
    part(new SphereGeometry(0.27, CAT_SEG.BIG, 11).scale(0.96, 1.42, 0.98), WHITE, [-0.03, 0.44, 0]),
    // 엉덩이 — 몸통 아래에 «반쯤 파묻어» 뒤로 퍼지게 한다. 경계가 안 생긴다
    part(new SphereGeometry(0.275, CAT_SEG.MID, 10).scale(1.02, 0.74, 1.06), WHITE, [-0.135, 0.225, 0]),
    // 가슴 — 앞으로 부푼다. 앞다리가 여기서 내려온다
    part(new SphereGeometry(0.185, CAT_SEG.MID, 9).scale(0.92, 1.15, 0.88), WHITE, [0.115, 0.40, 0]),
    /**
     * 머리 — **몸통에 박는다.** 몸통 꼭대기가 y 0.82, 머리 중심이 0.90, 반지름 0.205 라
     * 아래 절반이 몸통 안에 들어간다. 목을 따로 두지 않는 이유가 이것이다.
     */
    part(new SphereGeometry(0.205, CAT_SEG.MID, 9).scale(1.0, 0.96, 1.02), WHITE, [0.055, 0.905, 0]),
    // 볼 — 고양이 얼굴은 정수리보다 아래가 넓다. 매끈한 공은 인형이다
    ...([1, -1] as const).map((k) =>
      part(new SphereGeometry(0.105, CAT_SEG.SMALL, 6).scale(1.0, 0.82, 0.92), WHITE,
        [0.105, 0.845, k * 0.115])),
    /**
     * 귀 — **납작한 삼각형.** 정원뿔을 세우면 화면에서 «뿔»이고 실제로 그렇게 보였다.
     *
     * **누르는 축을 틀렸다.** 처음에 z(좌우)를 눌렀는데, 그러면 앞에서 볼 때
     * 귀가 «가늘어진다». 고양이 귀는 좌우로 넓고 앞뒤로 얇다 —
     * 눌러야 하는 건 x(앞뒤)다. 앞에서 봤을 때 무엇이 넓어야 하는지를
     * 먼저 정하고 축을 골라야 한다.
     *
     * 높이는 머리 높이의 45% — 사진에서 잰 값이다.
     */
    ...([1, -1] as const).flatMap((k) => [
      part(new ConeGeometry(0.112, 0.215, 5).scale(0.36, 1.0, 1.0), WHITE,
        [0.02, 1.145, k * 0.118], [k * 0.26, 0, 0]),
      part(new ConeGeometry(0.066, 0.135, 5).scale(0.36, 1.0, 1.0), [0.84, 0.50, 0.50],
        [0.038, 1.138, k * 0.120], [k * 0.26, 0, 0]),
    ]),
    /**
     * 얼굴 — **매끈한 셰이딩에서는 이목구비가 색으로만 읽힌다.**
     * 면이 안 보이니 코나 주둥이의 «솟음»은 실루엣에서만 보이고, 정면에서는
     * 오직 «색 대비»가 얼굴을 만든다. 판정자가 「눈·코 대신 진한 갈색 얼룩 하나」라고
     * 적은 건 눈이 옆으로 너무 벌어져 한쪽만 보였기 때문이다.
     *
     * 그래서 셋을 바꿨다:
     *   ① 눈을 **앞으로 모은다** — 고양이 눈은 옆이 아니라 앞을 본다(사냥꾼 눈)
     *   ② 눈을 키우고 **흰 테**를 두른다. 살구색 얼굴에 검은 점만 있으면 얼룩이다
     *   ③ 코 밑에 **입선**을 넣는다. 코 하나로는 얼굴 «가운데»가 안 잡힌다
     */
    part(new SphereGeometry(0.098, CAT_SEG.SMALL, 7).scale(1.20, 0.68, 1.24), [0.66, 0.57, 0.53],
      [0.208, 0.850, 0]),
    part(new SphereGeometry(0.040, SEG.TINY, 5).scale(1.15, 0.85, 1.0), [0.94, 0.46, 0.52],
      [0.268, 0.878, 0]),
    // 입선 — 코 밑 짧은 세로 홈. 이게 있어야 코가 「얼굴 가운데」가 된다
    part(new BoxGeometry(0.030, 0.052, 0.016), [0.48, 0.38, 0.36], [0.268, 0.828, 0]),
    ...([1, -1] as const).flatMap((k) => [
      // 흰 테 — 어두운 눈알만 두면 살구색 얼굴에서 「얼룩」이 된다
      part(new SphereGeometry(0.050, SEG.TINY, 5).scale(1.0, 1.12, 1.0), [1.28, 1.26, 1.18],
        [0.214, 0.958, k * 0.070]),
      part(new SphereGeometry(0.035, SEG.TINY, 5).scale(1.0, 1.18, 1.0), INK,
        [0.238, 0.960, k * 0.067]),
    ]),
    /**
     * 앞다리 — 가슴에서 곧게 내려와 발이 앞으로 나온다.
     * 이 세로선이 「앉았다」를 만든다.
     */
    ...([0.082, -0.082] as const).flatMap((z) => [
      part(new CylinderGeometry(0.056, 0.066, 0.40, CAT_SEG.SMALL), WHITE, [0.175, 0.20, z]),
      part(new SphereGeometry(0.072, CAT_SEG.SMALL, 6).scale(1.25, 0.62, 0.86), WHITE,
        [0.212, 0.038, z]),
    ]),
    // 꼬리 — 몸통을 감아 앞발 옆으로 돌아 나온다. 사진에서 본 것
    part(new TorusGeometry(0.235, 0.046, 4, 11, Math.PI * 1.1), WHITE, [-0.12, 0.070, 0],
      [Math.PI / 2, 0, 0.55]),
  ]),

  /**
   * 의자(쇼와 식탁 의자) — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/의자/` (빨간 비닐 좌판 · 등판 쇠파이프 의자 정면 · 뒤 3/4, 표기 W36 D43 H72 SH41 ·
   * 松戸市立博物館 常盤平団地 재현 전시)
   *
   * 앞의 것은 두꺼운 나무 좌판 · 판 등받이 · 네모 나무 다리였다. 사진과 대보니:
   *   ① 폭 : 깊이 : 높이 = **0.5 : 0.6 : 1**, 좌면 높이가 전체의 **0.57**
   *   ② 좌판은 폭의 0.057 두께 **얇은 빨간 비닐**, 등판은 높이 : 폭 = 0.65 인 둥근 모서리 판이
   *      좌판 위로 **틈(등판 폭의 0.30)을 두고 떠 있다** — 틈에는 쇠파이프 기둥 둘만
   *   ③ 뒷다리와 등판 기둥이 **한 가닥 파이프**로 좌판 높이에서 「く」자로 꺾여 뒤로 젖혀진다
   *   ④ 앞다리 사이 좌면 높이 0.69 에 가로 받침봉 하나, 파이프 굵기 약 1.9 cm 녹갈색
   * 나무 팔레트(7)에 곱하면 빨간 비닐이 갈색이 된다 — 팔레트는 흰색. 치수는 높이 = 1 로 쓴다(앞 +z).
   */
  의자: () => {
    const W = 0.5, D = 0.6, SEAT = 0.57, ST = 0.057 * W, R = 0.013, LEAN = 0.2;
    const RED: RGB = [0.90, 0.19, 0.15], PIPE: RGB = [0.30, 0.20, 0.10];
    const BACK_H = 0.65 * W * 0.9, GAP = 0.30 * W * 0.9;
    const yBack = SEAT + ST + GAP + BACK_H / 2, zBack = -D / 2 + 0.02 - Math.tan(LEAN) * (GAP + BACK_H / 2);
    const upH = GAP + BACK_H * 0.85;
    return assemble([
      // ② 얇은 비닐 좌판 + 처진 받침
      part(soft(W, ST, D * 0.9, 0.45), RED, [0, SEAT + ST / 2, 0.02]),
      part(new BoxGeometry(W * 0.8, 0.02, D * 0.7), [0.18, 0.14, 0.10], [0, SEAT - 0.012, 0.02]),
      // 등판 — 뒤로 젖힌 둥근 판
      part(soft(W * 0.9, BACK_H, 0.035, 0.45), RED, [0, yBack, zBack], [-LEAN, 0, 0]),
      // 앞다리 둘 + ④ 가로 받침봉
      ...([1, -1] as const).map((k) =>
        part(new CylinderGeometry(R, R, SEAT, 6), PIPE, [k * (W / 2 - 0.05), SEAT / 2, D / 2 - 0.08])),
      part(new CylinderGeometry(R * 0.9, R * 0.9, W - 0.1, 6), PIPE, [0, SEAT * 0.69, D / 2 - 0.08], [0, 0, Math.PI / 2]),
      // ③ 뒷다리 + 등판 기둥 — 좌판 높이에서 꺾여 뒤로 젖혀진다
      ...([1, -1] as const).flatMap((k) => [
        part(new CylinderGeometry(R, R, SEAT, 6), PIPE, [k * (W / 2 - 0.05), SEAT / 2, -D / 2 + 0.04]),
        part(new CylinderGeometry(R, R, upH, 6), PIPE,
          [k * (W / 2 - 0.12), SEAT + upH / 2, -D / 2 + 0.03 - Math.tan(LEAN) * upH / 2], [-LEAN, 0, 0]),
      ]),
      // 발끝 흰 마개
      ...([[1, 1], [-1, 1], [1, -1], [-1, -1]] as const).map(([kx, kz]) =>
        part(new CylinderGeometry(R * 1.2, R * 1.2, 0.02, 6), [0.92, 0.90, 0.85], [kx * (W / 2 - 0.05), 0.01, kz > 0 ? D / 2 - 0.08 : -D / 2 + 0.04])),
    ]);
  },

  /**
   * 스툴(쇼와 둥근 걸상) — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/스툴/` (초록 비닐 좌판 · 검은 쇠다리 정측면 · 빨간 비닐 크롬 다리 표기 357 × 430 mm · 밑면)
   *
   * 앞의 것은 두꺼운 나무 원판에 벌어진 나무 다리 넷과 가로대 둘이었다. 사진과 대보니:
   *   ① 좌판 지름 : 높이 = **1 : 1.2~1.4** — 앞의 것(1 : 0.95)보다 훨씬 높다
   *   ② 좌판은 지름의 **0.1** 두께에 가장자리가 둥글게 말린 **비닐 쿠션**
   *   ③ 다리는 벌어지지 않고 좌판 테두리 바로 안쪽에서 **곧게** 내려오는 가는 쇠파이프 넷(지름의 0.057),
   *      위끝이 둥글게 굽어 좌판 밑에서 **X자**로 엇갈린다. 가로대는 없다
   *   ④ 발끝의 밝은 마개(다리 굵기의 1.5배 높이)
   * 팔레트는 초록 · 빨강 비닐(11 · 8). 치수는 높이 = 1 로 쓴다.
   */
  스툴: () => {
    const H = 1, DIA = 1 / 1.3, SEAT_T = 0.1 * DIA, R = 0.057 * DIA / 2, LEGR = DIA / 2 - 0.035;
    // 사진(`ref/스툴/`)의 초록 비닐 좌판 (64,90,61) 과 검은 칠 쇠파이프 다리.
    // 팔레트를 흰색으로 옮겼으므로 색은 여기서 다 낸다
    const LEGC: RGB = [0.10, 0.10, 0.11], SEATC: RGB = [0.30, 0.44, 0.28];
    return assemble([
      // ② 비닐 쿠션 — 원판 + 둥글게 말린 가장자리
      part(new CylinderGeometry(DIA / 2 - SEAT_T / 2, DIA / 2 - SEAT_T / 2, SEAT_T, 14), SEATC, [0, H - SEAT_T / 2, 0]),
      part(new TorusGeometry(DIA / 2 - SEAT_T / 2, SEAT_T / 2, 4, 14), SEATC, [0, H - SEAT_T / 2, 0], LIE_Z),
      // ③ 다리 넷 — 곧게. 좌판 밑 X 틀
      ...[0, 1, 2, 3].map((k) => {
        const a = Math.PI / 4 + k * Math.PI / 2;
        return part(new CylinderGeometry(R, R, H - SEAT_T - 0.02, 6), LEGC, [Math.cos(a) * LEGR, (H - SEAT_T - 0.02) / 2, Math.sin(a) * LEGR]);
      }),
      ...[0, 1].map((k) =>
        part(new BoxGeometry(LEGR * 2, R * 2, R * 2), LEGC, [0, H - SEAT_T - 0.02, 0], [0, Math.PI / 4 + k * Math.PI / 2, 0])),
      // ④ 발끝 마개
      ...[0, 1, 2, 3].map((k) => {
        const a = Math.PI / 4 + k * Math.PI / 2;
        return part(new CylinderGeometry(R * 1.15, R * 1.15, R * 3, 6), [0.92, 0.92, 0.90], [Math.cos(a) * LEGR, R * 1.5, Math.sin(a) * LEGR]);
      }),
    ]);
  },

  /**
   * 브라운관 TV — **실물 사진을 보고 다시 만들었다.**
   * 근거: `.design-bounce/ref/텔레비전/` (위키미디어)
   *
   * 정답을 모르는 판정자가 근거에 「검은 상자 앞면에 **큰 검은 사각 패널**」이라고
   * 적었다. 이름은 맞혔지만 화면과 캐비닛이 한 덩어리라는 뜻이다.
   *
   * 사진에서 확인한 둘:
   *   ① **꺼진 화면은 검정이 아니라 옅은 회녹색이다.** 검정 캐비닛에 검정 화면을
   *      넣으면 안테나만 남는다. 팔레트를 검정(5)에서 나무(7)로 옮기고
   *      화면을 «밝은» 쪽으로 보낸다 — 정점색이 곱하는 계수라 나무 위에서
   *      회녹색을 만들려면 파랑 계수가 1을 크게 넘어야 한다
   *   ② **화면은 앞판의 71%만 차지한다.** 나머지 오른쪽은 튜너 다이얼과
   *      세로살 스피커망이 있는 조작판 «기둥»이다. 앞판을 화면으로 다 덮으면
   *      옛날 텔레비전이 아니라 요즘 모니터가 된다
   */
  텔레비전: () => assemble([
    /**
     * 캐비닛 — 나뭇결. 사진에서 잰 가로:세로 = **1 : 0.69**.
     * 앞의 것은 0.86 × 0.66 = 1 : 0.77 이라 거의 정육면체로 보였다.
     * 깊이도 줄인다 — 브라운관은 뒤가 튀어나오지만 앞에서 볼 때 두꺼우면 상자다.
     */
    part(soft(0.94, 0.65, 0.56, 0.13), WHITE, [0, 0.415, 0], undefined, TILE.WOOD_C),
    // 검은 베젤 — 화면이 이 «안쪽»으로 움푹 들어가야 유리로 읽힌다
    part(new BoxGeometry(0.655, 0.535, 0.035), [0.26, 0.27, 0.30], [-0.115, 0.435, 0.285],
      undefined, TILE.PANEL),
    /**
     * 화면 유리. 나무 팔레트(0.60, 0.42, 0.25)에 이 계수를 곱하면
     * (0.73, 0.79, 0.75) — 옅은 회녹색이 된다. 사진의 꺼진 브라운관 색이다.
     */
    part(new BoxGeometry(0.575, 0.455, 0.03), [1.22, 1.88, 3.00], [-0.115, 0.435, 0.306],
      undefined, TILE.SCREEN),
    /**
     * 오른쪽 조작판 기둥. 사진에서 앞판의 29%를 차지하고 화면과 «세로로 갈린다».
     * 황동빛이라 캐비닛보다 밝고 노랗다.
     */
    part(new BoxGeometry(0.205, 0.535, 0.028), [1.34, 1.42, 0.92], [0.335, 0.435, 0.286],
      undefined, TILE.PANEL),
    // 튜너 다이얼 — 눈금 링이 둘린 원형 손잡이. 기둥 «위쪽»에 하나뿐이다
    part(new CylinderGeometry(0.074, 0.074, 0.03, 12), [1.55, 1.62, 1.05],
      [0.335, 0.585, 0.306], LIE_Z, TILE.PANEL),
    part(new CylinderGeometry(0.030, 0.030, 0.045, 8), INK, [0.335, 0.585, 0.315], LIE_Z),
    /**
     * 스피커망 — **촘촘한 세로살**이다. 사진에서 다이얼 아래를 길게 채운다.
     * 살 다섯이면 「망」으로 읽히고 삼각형도 안 늘어난다.
     */
    ...([-0.068, -0.034, 0, 0.034, 0.068] as const).map((dx) =>
      part(new BoxGeometry(0.012, 0.30, 0.012), INK, [0.335 + dx, 0.325, 0.300])),
    /**
     * 안테나. 팔레트를 검정에서 «나무»로 옮겼으므로 계수도 같이 바꾼다 —
     * `SHINE`(2.6, 2.55, 2.4)을 나무(0.60, 0.42, 0.25)에 곱하면 주황빛으로 포화된다.
     * 파랑 쪽을 더 올려 은색으로 뺀다: (0.60, 0.42, 0.25) × 아래 = (0.99, 0.97, 0.90)
     */
    ...([[0.17, 0.3], [-0.17, -0.3]] as const).map(([x, rz]) =>
      part(new CylinderGeometry(0.022, 0.016, 0.52, 6), [1.65, 2.30, 3.60],
        [x, 0.96, -0.14], [0.3, 0, rz])),
    ...([0.34, -0.34] as const).map((x) =>
      part(soft(0.10, 0.13, 0.10, 0.3), WHITE, [x, 0.045, 0.18])),
  ]),

  /**
   * 서랍장 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/서랍장/` (古家具 3단 서랍장 정면, 가게 치수 630 × 630mm)
   *
   * 앞의 것은 폭 0.83 : 높이 1 의 세로로 긴 몸통에 서랍마다 은색 둥근 손잡이 둘이었다.
   *   ① **폭과 높이가 같다**(1 : 0.98) — 낮고 네모나다
   *   ② 서랍 셋의 높이가 위부터 전체의 0.28 · 0.25 · 0.24 로 거의 같다
   *   ③ 손잡이는 서랍마다 **한가운데 하나**, 서랍 폭 0.21 짜리 가로 나무 막대. 금속이 아니다
   *   ④ 맨 아래 **짙은 적갈색 걸레받이 띠**(0.066)와 받침 몰딩(0.047)
   *   ⑤ 옆판·앞 기둥이 서랍 앞판보다 훨씬 짙다 — 서랍 묶음을 짙은 액자가 두른다
   * 깊이는 사진이 비스듬해 못 쟀다. **예전 발자국 깊이(0.54)를 그대로 둔다** — 서벽에 붙어 서 있어서
   * 깊어지면 벽을 파고든다. 윗면이 1.00 → 0.96 으로 내려가 `surf-chest` 높이를 같이 맞췄다.
   * 색은 팔레트(나무 0x9a6b3f)에 곱하는 계수로, 사진의 RGB 를 팔레트로 나눠 잡았다.
   */
  서랍장: () => {
    const W = 1, H = 0.98, D = 0.52;
    const FRAME: RGB = [0.69, 0.49, 0.38];       // (106,52,24)
    const FRONT: RGB = [1.34, 1.14, 1.12];       // 붉은 기 도는 호박색 소나무 — 1.46 계열은 게임 조명에서 누렇게 떴다
    const PULL: RGB = [1.00, 0.72, 0.60];        // 앞판보다 확실히 짙은 갈색 — 사진 손잡이는 몸통 틀 색에 가깝다
    const BASEBOARD: RGB = [0.96, 0.69, 0.57];   // (148,74,36)
    // 아래부터 잰 높이 (전체 = 1)
    const MOLD = 0.047, BOARD = 0.066, SEP3 = 0.016, DR3 = 0.2375, SEP2 = 0.025, DR2 = 0.25,
      SEP1 = 0.019, DR1 = 0.278, TOP = 0.056;
    const y3 = MOLD + BOARD + SEP3, y2 = y3 + DR3 + SEP2, y1 = y2 + DR2 + SEP1;
    const drawers: [number, number][] = [[y3, DR3], [y2, DR2], [y1, DR1]];
    return assemble([
      // 몸통 — 짙은 옆판·기둥. 서랍 사이 칸막이가 이 색으로 보인다
      part(soft(W, H * (1 - TOP), D, 0.04), FRAME, [0, H * (1 - TOP) / 2, 0], undefined, TILE.WOOD_C),
      // 윗판 — 얇고 옆판과 거의 같은 선. 두껍게 튀어나오면 판정자가 「둥근 윗판이 크게 튀어나왔다」고 한다
      part(soft(W + 0.006, H * TOP, D + 0.012, 0.12), [1.05, 0.86, 0.80], [0, H * (1 - TOP / 2), 0.006], undefined, TILE.WOOD_C),
      // ④ 걸레받이 + 몰딩
      part(new BoxGeometry(W - 0.05, H * BOARD, 0.012), BASEBOARD, [0, H * (MOLD + BOARD / 2), D / 2 + 0.006]),
      part(soft(W + 0.01, H * MOLD, D + 0.01, 0.3), FRAME, [0, H * MOLD / 2, 0]),
      // ② 서랍 앞판 셋 + ③ 가운데 나무 막대 손잡이
      ...drawers.flatMap(([y, h]) => [
        // 서랍 앞판 — 옆 기둥(폭의 0.05)과 칸막이 틀 «안»에 들어간다. 꽉 채우면 틀이 안 보인다
        part(new BoxGeometry(W * 0.90, H * h * 0.94, 0.014), FRONT, [0, H * (y + h / 2), D / 2 + 0.007],
          undefined, TILE.WOOD_C),
        // ③ 손잡이 — 반원통 막대, 양 끝이 비스듬히 깎여 윗변이 아랫변보다 길다
        part(warp(new CylinderGeometry(0.036, 0.036, W * 0.21, 10), (x, yy, z) => [x, yy * (x > 0 ? 1 : 0.72), z]),
          PULL, [0, H * (y + h / 2), D / 2 + 0.02], [0, 0, Math.PI / 2]),
      ]),
      // 맨 아래 서랍의 열쇠 구멍
      part(new BoxGeometry(0.012, 0.02, 0.006), INK, [0, H * (y3 + DR3 * 0.82), D / 2 + 0.015]),
    ]);
  },

  /**
   * 스탠드 — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/스탠드/` (ミツボシ 플로어 스탠드, 가게 치수 높이 155.5 · 폭 35.5cm)
   *
   * 앞의 것은 **갓이 위아래로 뒤집혀 있었다** — `CylinderGeometry(0.23, 0.14, …)` 는
   * 위 반지름을 먼저 받아서 위가 넓은 원뿔대가 됐고, 위아래 테는 아래가 넓은 갓에 맞춰져
   * 있어서 아래 테가 허공에 떠 있었다. 그리고 갓 지름이 키의 0.46 으로 **두 배 넓었다.**
   *   ① 갓은 **아래가 넓다** — 위 : 아래 : 높이 = 0.67 : 1 : 0.68, 아래 지름 = 키의 0.23
   *   ② 가는 **나무 기둥**이 키의 0.73 — 굵기는 갓 아래 지름의 0.08, 가운데 금색 이음 링
   *   ③ 받침은 **납작한 금색 원판** — 갓 아래 지름의 0.78
   *   ④ 갓 위아래에 금갈색 가는 테
   * 치수는 키 = 1 로 쓴다. 갓이 좁아져서 예전 충돌 상자 문제(아래 기록)는 더 멀어졌다.
   *
   * > 예전 기록: 갓 지름 0.68 일 때 손배치 스탠드(size 1.20)의 AABB 가 0.83m 라
   * > 거실 동벽을 0.21m 뚫고 `spot-shelf-front` 를 덮었다.
   */
  스탠드: () => {
    const SHADE: RGB = [1.00, 0.94, 0.74];   // 상아색 천 — 불빛이 비쳐 따뜻하다
    const WOODEN: RGB = [0.50, 0.27, 0.04];  // 꿀색 나무 기둥
    const BRASS: RGB = [0.98, 0.78, 0.26];   // 번쩍이는 황동 — 0.62 계열은 「회갈색」으로 읽혔다
    const TRIM: RGB = [0.70, 0.62, 0.31];    // 금갈색 테 (170,151,75)
    const R_BOT = 0.1126, R_TOP = 0.0754, S_BOT = 0.826, S_TOP = 0.979;
    const S_H = S_TOP - S_BOT, S_Y = (S_TOP + S_BOT) / 2;
    /**
     * **삼각형을 아낀다.** 스탠드는 길거리 규모 씬에 210개 깔려서 형태 하나 +100 이 씬 +21,000 이다.
     * 1cm 도 안 되는 부품(이음 링 · 꼭대기 고리 · 고무 테)은 이 크기에서 안 보이므로 뺐고,
     * 테는 단면 3각, 갓은 16면이다.
     */
    return assemble([
      // ③ 받침 — 납작한 금색 원판
      part(new CylinderGeometry(0.085, 0.087, 0.027, 16), BRASS, [0, 0.0135, 0]),
      // 기둥 가운데 금색 이음 링 — 210개가 깔려 받침 위 링은 뺐다
      part(new TorusGeometry(0.0105, 0.0035, 3, 10), BRASS, [0, 0.424, 0], LIE_Z),
      // 받침 위 항아리 모양 발목
      part(new CylinderGeometry(0.009, 0.013, 0.038, 8, 1, true), WOODEN, [0, 0.046, 0]),
      // ② 나무 기둥 + 갓 밑 황동 대롱
      part(new CylinderGeometry(0.0093, 0.0093, 0.69, 8, 1, true), WOODEN, [0, 0.065 + 0.345, 0], undefined, TILE.WOOD_F),
      part(new CylinderGeometry(0.0068, 0.0068, 0.08, 6, 1, true), BRASS, [0, 0.79, 0]),
      // 전구 — 갓 안에서 켜져 있다
      part(new SphereGeometry(0.03, 8, 5), WRAP, [0, 0.85, 0]),
      // ① 갓 — 아래가 넓은 원뿔대. 위 반지름을 «먼저» 쓴다
      // 천 결 인쇄는 뺐다 — 격자로 읽혀 판정자가 「바구니」라고 했다
      part(new CylinderGeometry(R_TOP, R_BOT, S_H, 16, 1, true), SHADE, [0, S_Y, 0]),
      // 갓 안쪽 — 불이 켜져 밝다. 안을 보게 뒤집는다
      part(invert(new CylinderGeometry(R_TOP - 0.002, R_BOT - 0.002, S_H, 16, 1, true)), WRAP, [0, S_Y, 0]),
      // 갓 윗면 — 천을 덮은 원판(윗면만)
      part(new CircleGeometry(R_TOP, 16), SHADE, [0, S_TOP, 0], [-Math.PI / 2, 0, 0]),
      // ④ 위아래 테 — 넓은 쪽이 아래
      part(new TorusGeometry(R_BOT, 0.0035, 3, 16), TRIM, [0, S_BOT, 0], LIE_Z),
      part(new TorusGeometry(R_TOP, 0.003, 3, 16), TRIM, [0, S_TOP, 0], LIE_Z),
    ]);
  },

  /**
   * 물뿌리개(함석) — **사진에서 잰 값으로 다시 만들었다.**
   * 근거: `.design-bounce/ref/물뿌리개/` (오래된 아연 도금 물뿌리개 정옆)
   *
   * 앞의 것은 아래가 넓은 원뿔대 몸통에 굵은 주둥이가 몸통 가운데서 나오는 것이었다. 사진과 대보니:
   *   ① 높이 : 지름 = **1.38 : 1** 의 **곧은 원통** 몸통, 테에서 0.45 아래를 한 바퀴 두른 볼록 띠
   *   ② 주둥이는 몸통 **아래쪽(테에서 0.76)** 에서 **49°** 로 뻗는 **몸통 지름 2배** 길이의 가는 관(지름의 0.12),
   *      끝에 **나팔꼴 꼭지**(얼굴 지름 = 몸통 지름의 0.44)
   *   ③ 주둥이와 몸통을 잇는 **수평 버팀대**(테에서 0.19 아래)
   *   ④ 윗면 가운데 몸통 높이의 0.40 만큼 솟은 **띠쇠 고리 손잡이**와 몸통 뒤로 지름의 0.30 튀어나온 **뒷손잡이**
   * 주황 · 초록 팔레트(9 · 11)는 사진의 도금 회색을 못 낸다 — 흰색 팔레트에 함석 인쇄(`TILE.SPANGLE`).
   * 거리에 216개라 면 수를 아꼈다(원기둥 14면). 치수는 몸통 지름 = 1 로 쓴다(주둥이 +x).
   */
  물뿌리개: () => {
    const D = 1, H = 1.38, R = D / 2, ZINC: RGB = [0.78, 0.82, 0.80];
    const SP_Y = H * (1 - 0.76), SP_L = 2.05 * D, SP_A = 49 * Math.PI / 180, SP_R = 0.06;
    const tip: [number, number, number] = [R + Math.cos(SP_A) * SP_L, SP_Y + Math.sin(SP_A) * SP_L, 0];
    return assemble([
      // ① 몸통 · 바닥 · 볼록 띠 · 테
      part(new CylinderGeometry(R, R * 0.97, H, 14, 1, true), ZINC, [0, H / 2, 0], undefined, TILE.SPANGLE),
      part(new CircleGeometry(R, 14), [0.55, 0.57, 0.56], [0, 0.002, 0], [Math.PI / 2, 0, 0]),
      part(new TorusGeometry(R + 0.005, 0.02, 3, 14), ZINC, [0, H * (1 - 0.45), 0], LIE_Z),
      part(new TorusGeometry(R, 0.018, 3, 14), [0.72, 0.75, 0.74], [0, H, 0], LIE_Z),
      // 윗면 — 앞 절반을 덮은 둥근 덮개, 뒤는 짙은 물구멍
      part(new SphereGeometry(R, 10, 3, 0, Math.PI, 0, Math.PI / 2).scale(1, 0.3, 1), ZINC, [0, H, 0], [0, -Math.PI / 2, 0]),
      part(new CircleGeometry(R * 0.9, 10, Math.PI / 2, Math.PI), [0.22, 0.24, 0.24], [0, H + 0.004, 0], [-Math.PI / 2, 0, 0]),
      // ② 주둥이 관 + 나팔꼴 꼭지
      part(new CylinderGeometry(SP_R, SP_R, SP_L, 6), ZINC,
        [R + Math.cos(SP_A) * SP_L / 2, SP_Y + Math.sin(SP_A) * SP_L / 2, 0], [0, 0, SP_A - Math.PI / 2]),
      part(new CylinderGeometry(0.22, SP_R, 0.40, 10, 1, true), ZINC, tip, [0, 0, SP_A - Math.PI / 2]),
      part(new CircleGeometry(0.22, 10), [0.60, 0.63, 0.62], [tip[0] + Math.cos(SP_A) * 0.2, tip[1] + Math.sin(SP_A) * 0.2, 0], [0, 0, SP_A - Math.PI / 2 - Math.PI / 2]),
      // ③ 수평 버팀대 — 테에서 0.19 아래, 몸통 → 관
      part(new BoxGeometry(0.62, 0.03, 0.05), ZINC, [R + 0.30, H * (1 - 0.19), 0]),
      // ④ 윗손잡이(띠쇠 고리) · 뒷손잡이
      part(new TorusGeometry(0.175, 0.03, 3, 8, Math.PI), ZINC, [0, H, 0]),
      part(new TorusGeometry(0.30, 0.03, 3, 8, Math.PI), ZINC, [-R, H * 0.72, 0], [0, 0, Math.PI / 2]),
    ]);
  },
};
